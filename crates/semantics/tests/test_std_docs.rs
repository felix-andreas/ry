//! Generates the standard library's API pages under `docs/src/content/docs/reference/std/` from
//! `types/std.Rtypes`, and fails when the committed pages differ from what the file generates.
//!
//! `types/std.Rtypes` is the single source of truth: the checker reads its declarations and hover
//! shows its `#'` lines, so the pages are rendered from it and never edited by hand. Run
//! `just docs-std` (or this test with `RY_BLESS=1`) to rewrite them.

use std::{
    fs,
    path::{Path, PathBuf},
};

const SOURCE_URL: &str = "https://github.com/felix-andreas/ry/blob/main/types/std.Rtypes";
const GENERATED_NOTICE: &str =
    "{/* Generated from types/std.Rtypes by `just docs-std`. Do not edit this file. */}";

#[test]
fn standard_library_pages_are_current() -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let source =
        fs::read_to_string(root.join("types/std.Rtypes")).map_err(|error| error.to_string())?;
    let library = parse_library(&source)?;
    let pages = render_pages(&library);
    let directory = root.join("docs/src/content/docs/reference/std");
    let bless =
        std::env::var_os("RY_BLESS").is_some() || std::env::var_os("ROUGHLY_BLESS").is_some();
    if bless {
        if directory.exists() {
            fs::remove_dir_all(&directory).map_err(|error| error.to_string())?;
        }
        fs::create_dir_all(&directory).map_err(|error| error.to_string())?;
        for (name, contents) in &pages {
            fs::write(directory.join(name), contents).map_err(|error| error.to_string())?;
        }
        return Ok(());
    }
    let mut stale = Vec::new();
    for (name, contents) in &pages {
        let path: PathBuf = directory.join(name);
        if fs::read_to_string(&path).ok().as_deref() != Some(contents.as_str()) {
            stale.push(name.clone());
        }
    }
    let mut committed: Vec<String> = fs::read_dir(&directory)
        .map_err(|error| format!("{}: {error}; run `just docs-std`", directory.display()))?
        .filter_map(|entry| {
            entry
                .ok()
                .map(|entry| entry.file_name().to_string_lossy().into_owned())
        })
        .collect();
    committed.sort();
    for name in committed {
        if !pages.iter().any(|(page, _)| *page == name) {
            stale.push(format!("{name} (no longer generated)"));
        }
    }
    if stale.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "the standard library pages are out of date with types/std.Rtypes: {}. Run `just docs-std`.",
            stale.join(", ")
        ))
    }
}

struct Library {
    modules: Vec<Module>,
}

struct Module {
    name: String,
    docs: Vec<String>,
    types: Vec<String>,
    items: Vec<Item>,
}

struct Item {
    name: String,
    line: usize,
    signatures: Vec<String>,
    docs: Vec<String>,
}

fn parse_library(source: &str) -> Result<Library, String> {
    let mut modules: Vec<Module> = Vec::new();
    let mut types: Vec<String> = Vec::new();
    let mut pending: Vec<String> = Vec::new();
    for (index, line) in source.lines().enumerate() {
        let number = index + 1;
        if let Some(doc) = line.strip_prefix("#'") {
            pending.push(doc.strip_prefix(' ').unwrap_or(doc).to_owned());
        } else if let Some(heading) = line.strip_prefix("# ").filter(|rest| is_module_name(rest)) {
            modules.push(Module {
                name: heading.to_owned(),
                docs: std::mem::take(&mut pending),
                types: Vec::new(),
                items: Vec::new(),
            });
        } else if let Some(declaration) = line.strip_prefix('@') {
            if !pending.is_empty() {
                return Err(format!(
                    "line {number}: `#'` documentation above a type declaration is not rendered"
                ));
            }
            types.push(format!("@{declaration}"));
        } else if let Some((name, signature)) = line.split_once(" : ") {
            let module = modules.last_mut().ok_or_else(|| {
                format!("line {number}: `{name}` is declared before any `# Module` heading")
            })?;
            let docs = std::mem::take(&mut pending);
            match module.items.last_mut() {
                Some(item) if item.name == name && docs.is_empty() => {
                    item.signatures.push(signature.to_owned())
                }
                _ if docs.is_empty() => {
                    return Err(format!("line {number}: `{name}` has no `#'` documentation"));
                }
                _ => module.items.push(Item {
                    name: name.to_owned(),
                    line: number,
                    signatures: vec![signature.to_owned()],
                    docs,
                }),
            }
        } else if !line.trim().is_empty() && !line.starts_with('#') {
            return Err(format!("line {number}: unexpected line `{line}`"));
        } else if line.trim().is_empty() {
            if !pending.is_empty() {
                return Err(format!(
                    "line {number}: a blank line separates `#'` documentation from its declaration"
                ));
            }
        } else {
            pending.clear();
        }
    }
    for declaration in types {
        let type_name: String = declaration
            .split_whitespace()
            .nth(1)
            .map(|name| {
                name.chars()
                    .take_while(|character| character.is_alphanumeric())
                    .collect()
            })
            .unwrap_or_default();
        if let Some(module) = modules.iter_mut().find(|module| module.name == type_name) {
            module.types.push(declaration);
        }
    }
    Ok(Library { modules })
}

fn is_module_name(text: &str) -> bool {
    text.chars()
        .next()
        .is_some_and(|character| character.is_ascii_uppercase())
        && text
            .chars()
            .all(|character| character.is_ascii_alphanumeric())
}

fn render_pages(library: &Library) -> Vec<(String, String)> {
    let mut pages = vec![("index.mdx".to_owned(), render_index(library))];
    for module in &library.modules {
        pages.push((
            format!("{}.mdx", module.name.to_lowercase()),
            render_module(module),
        ));
    }
    pages
}

fn render_index(library: &Library) -> String {
    let mut page = String::new();
    page.push_str("---\ntitle: std\ndescription: The API of ry's standard library, module by module.\n---\n\n");
    page.push_str(GENERATED_NOTICE);
    page.push_str("\n\n");
    page.push_str(
        "ry's standard library is the `std` namespace. With the prelude on, the default, every function \
         is also in scope by its bare name, such as `List.map`; with `[check] prelude = false` it is \
         reachable only as `std::List.map`. The [standard library guide](/reference/standard-library/) \
         covers the conventions the modules share.\n\n",
    );
    page.push_str("| Module | Functions | Summary |\n| --- | --- | --- |\n");
    for module in &library.modules {
        page.push_str(&format!(
            "| [`{name}`](/reference/std/{slug}/) | {count} | {summary} |\n",
            name = module.name,
            slug = module.name.to_lowercase(),
            count = module.items.len(),
            summary = table_cell(&first_sentence(&module.docs)),
        ));
    }
    page
}

fn render_module(module: &Module) -> String {
    let mut page = String::new();
    page.push_str(&format!(
        "---\ntitle: {name}\ndescription: The `{name}` module of ry's standard library.\n---\n\n",
        name = module.name
    ));
    page.push_str("import { Tabs, TabItem } from '@astrojs/starlight/components';\n\n");
    page.push_str(GENERATED_NOTICE);
    page.push_str("\n\n");
    for line in &module.docs {
        page.push_str(line);
        page.push('\n');
    }
    if !module.types.is_empty() {
        page.push_str("\n```\n");
        for declaration in &module.types {
            page.push_str(declaration);
            page.push('\n');
        }
        page.push_str("```\n");
    }
    page.push_str("\n| Function | Summary |\n| --- | --- |\n");
    for item in &module.items {
        page.push_str(&format!(
            "| [`{name}`](#{slug}) | {summary} |\n",
            name = item.name,
            slug = slug(&item.name),
            summary = table_cell(&first_sentence(&item.docs)),
        ));
    }
    for item in &module.items {
        render_item(&mut page, item);
    }
    page
}

fn render_item(page: &mut String, item: &Item) {
    page.push_str(&format!("\n## `{}`\n\n", item.name));
    let inline: Option<Vec<String>> = item
        .signatures
        .iter()
        .map(|signature| inline_signature(&item.name, signature))
        .collect();
    let comments: Vec<String> = item
        .signatures
        .iter()
        .map(|signature| comment_signature(&item.name, signature))
        .collect();
    match inline {
        Some(inline) => {
            page.push_str(
                "<Tabs syncKey=\"annotation-style\">\n<TabItem label=\"Inline\">\n\n```r\n",
            );
            page.push_str(&inline.join("\n"));
            page.push_str("\n```\n\n</TabItem>\n<TabItem label=\"Comments\">\n\n```r\n");
            page.push_str(&comments.join("\n\n"));
            page.push_str("\n```\n\n</TabItem>\n</Tabs>\n\n");
        }
        None => {
            page.push_str("```r\n");
            page.push_str(&comments.join("\n\n"));
            page.push_str("\n```\n\n");
        }
    }
    for line in &item.docs {
        let fence = line.strip_prefix("```r").map(str::trim);
        match fence {
            Some("") => page.push_str("```r ry run runtime=ry"),
            Some(options) => page.push_str(&format!("```r ry run runtime=ry {options}")),
            None => page.push_str(line),
        }
        page.push('\n');
    }
    page.push_str(&format!("\n[Source]({SOURCE_URL}#L{})\n", item.line));
}

/// The declaration as an inline function header, or `None` for a constant or a function with an
/// optional parameter, which inline syntax writes with a default value the declaration does not
/// state.
fn inline_signature(name: &str, signature: &str) -> Option<String> {
    let (generics, function) = match signature.strip_prefix('<') {
        Some(rest) => {
            let end = matching_close(rest, '<', '>')?;
            (
                format!("<{}>", rest.get(..end)?),
                rest.get(end + 1..)?.trim_start(),
            )
        }
        None => (String::new(), signature),
    };
    // A constant has no inline header: `Num.pi: double` alone is an expression, not a declaration.
    let rest = function.strip_prefix("fn(")?;
    let end = matching_close(rest, '(', ')')?;
    let parameters = rest.get(..end)?;
    if parameters.contains('[') && parameters.contains("]:") {
        return None;
    }
    let result = rest
        .get(end + 1..)?
        .trim_start()
        .strip_prefix("->")?
        .trim_start();
    Some(format!(
        "{name} <- function{generics}({parameters}) -> {result}"
    ))
}

fn comment_signature(name: &str, signature: &str) -> String {
    let parameters = signature.find("fn(").and_then(|start| {
        let rest = signature.get(start + 3..)?;
        let end = matching_close(rest, '(', ')')?;
        Some(parameter_names(rest.get(..end)?))
    });
    match parameters {
        Some(parameters) => format!("#: {signature}\n{name} <- function({parameters})"),
        None => format!("#: {signature}\n{name}"),
    }
}

fn parameter_names(parameters: &str) -> String {
    split_top_level(parameters)
        .iter()
        .filter_map(|parameter| parameter.split_once(':').map(|(name, _)| name.trim()))
        .map(|name| {
            name.trim_start_matches('[')
                .trim_end_matches(']')
                .to_owned()
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn split_top_level(text: &str) -> Vec<&str> {
    let mut parts = Vec::new();
    let mut depth = 0i32;
    let mut start = 0;
    for (index, character) in text.char_indices() {
        match character {
            '(' | '<' | '[' | '{' => depth += 1,
            ')' | ']' | '}' => depth -= 1,
            '>' if !text
                .get(..index)
                .is_some_and(|before| before.ends_with('-')) =>
            {
                depth -= 1
            }
            ',' if depth == 0 => {
                parts.push(text.get(start..index).unwrap_or_default().trim());
                start = index + 1;
            }
            _ => {}
        }
    }
    let last = text.get(start..).unwrap_or_default().trim();
    if !last.is_empty() {
        parts.push(last);
    }
    parts
}

/// The byte offset of the bracket that closes an already opened `open`, skipping `->` arrows.
fn matching_close(text: &str, open: char, close: char) -> Option<usize> {
    let mut depth = 1i32;
    for (index, character) in text.char_indices() {
        let arrow = character == '>'
            && text
                .get(..index)
                .is_some_and(|before| before.ends_with('-'));
        if character == open {
            depth += 1;
        } else if character == close && !arrow {
            depth -= 1;
            if depth == 0 {
                return Some(index);
            }
        }
    }
    None
}

fn first_sentence(docs: &[String]) -> String {
    let paragraph: Vec<&str> = docs
        .iter()
        .map(String::as_str)
        .take_while(|line| !line.trim().is_empty())
        .collect();
    let text = paragraph.join(" ");
    let mut in_code = false;
    for (index, character) in text.char_indices() {
        if character == '`' {
            in_code = !in_code;
        } else if character == '.'
            && !in_code
            && text
                .get(index + 1..)
                .is_none_or(|rest| rest.is_empty() || rest.starts_with(' '))
        {
            return text.get(..=index).unwrap_or(&text).to_owned();
        }
    }
    text
}

fn table_cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// The anchor Starlight gives a heading that is only the code span `name`.
fn slug(name: &str) -> String {
    name.chars()
        .filter(|character| character.is_alphanumeric() || *character == '_' || *character == '-')
        .flat_map(char::to_lowercase)
        .collect()
}
