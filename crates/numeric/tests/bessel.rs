//! `besselI`, `besselJ`, `besselK` and `besselY` against GNU R 4.6.2, bit for bit. Each table
//! holds GNU R's result for every `(x, nu)` of the grid below, in x-major order, as the bits of
//! the double (generated with `writeBin` from `Rscript`).

use numeric::rmath::{bessel_i, bessel_j, bessel_k, bessel_y, take_warnings};

const XS: [f64; 21] = [
    0.0,
    1e-300,
    1e-10,
    0.1,
    0.5,
    1.0,
    2.0,
    5.0,
    10.0,
    19.9,
    20.0,
    25.0,
    50.0,
    100.0,
    1e3,
    1e4,
    1e5,
    1e8,
    f64::INFINITY,
    f64::NAN,
    -1.0,
];

const NUS: [f64; 16] = [
    0.0, 0.25, 0.5, 1.0, 1.5, 2.0, 3.7, 10.0, 30.5, 100.0, 1000.0, -0.5, -1.0, -1.3, -2.5, -10.0,
];

fn check(name: &str, expected: &[u64], function: impl Fn(f64, f64) -> f64) {
    let mut mismatches = Vec::new();
    let cells = XS.iter().flat_map(|&x| NUS.iter().map(move |&nu| (x, nu)));
    for ((x, nu), &bits) in cells.zip(expected) {
        let want = f64::from_bits(bits);
        let got = function(x, nu);
        if !(got.to_bits() == bits || (got.is_nan() && want.is_nan())) {
            mismatches.push(format!("{name}({x:e}, {nu}): got {got:e}, GNU R {want:e}"));
        }
    }
    take_warnings();
    assert!(mismatches.is_empty(), "{}", mismatches.join("\n"));
}

#[test]
fn bessel_j_matches_gnu_r() {
    check("besselJ", &J, bessel_j);
}

#[test]
fn bessel_y_matches_gnu_r() {
    check("besselY", &Y, bessel_y);
}

#[test]
fn bessel_i_matches_gnu_r() {
    check("besselI", &I, |x, nu| bessel_i(x, nu, 1.0));
    check("besselI scaled", &ISCALED, |x, nu| bessel_i(x, nu, 2.0));
}

#[test]
fn bessel_k_matches_gnu_r() {
    check("besselK", &K, |x, nu| bessel_k(x, nu, 1.0));
    check("besselK scaled", &KSCALED, |x, nu| bessel_k(x, nu, 2.0));
}

