# Long string results whose pieces repeat, past the point where substr and formatC start sharing
# equal pieces within one call, and all-distinct pieces where the sharing turns itself off.
set.seed(11)
n <- 200000L
words <- c("alpha", "beta", "gamma", "delta", "été", "über")
x <- sample(words, n, replace = TRUE)
pieces <- substr(x, 1L, 3L)
table(pieces)
head(pieces, 8)
tail(pieces, 8)
sum(nchar(pieces))
distinct <- substr(sprintf("%07d-key", seq_len(n)), 1L, 7L)
length(unique(distinct))
head(distinct, 3)
tail(distinct, 3)
mixed <- substr(c(x, sprintf("%06d", seq_len(n))), 2L, 4L)
length(unique(mixed))
sum(nchar(mixed))
values <- round(runif(n, 0, 50))
formatted <- formatC(values, width = 6, format = "f", digits = 1)
table(nchar(formatted))
head(formatted, 5)
length(unique(formatted))
wide <- formatC(runif(n), format = "e", digits = 4)
length(unique(wide))
head(wide, 3)
