# fread gives the same table whether ry's reader or data.table's own answers.
library(data.table)
path <- tempfile(fileext = ".csv")
show <- function(text) {
  writeLines(text, path)
  x <- fread(path)
  print(sapply(x, function(column) paste(class(column), collapse = "/")))
  dput(as.list(x))
  print(names(attributes(x)))
  print(key(x))
  print(x)
  invisible(NULL)
}
show(c("id,n,v,flag,s,empty", "a,1,0.5,TRUE,x,", "b,NA,1e3,FALSE,,", "c,3,-2.25,NA,NA,"))
show(c("g,big,small", "k,3000000000,1", "l,1,2"))
show(c("day,v", "2024-01-02,1", "2024-01-03,2"))
show(c("when,v", "2024-01-02T10:00:00Z,1", "2024-01-03T11:00:00Z,2"))
show(c("name,v", "\"quoted, comma\",1", "plain,2"))
show(c("name,v", " padded ,1", "plain,2"))
show(c("code,v", "007,1", "010,2"))
show(c("x,y", "T,1", "F,2"))
show(c("x,y", "true,1", "false,2"))
show(c("x,y", "Inf,1", "-Inf,NaN"))
show(c("x,y", "1,a", "2.5,b", "3,c"))
show(c("x,y", "1-2,a", "3-4,b"))
show(c("only", "1", "2"))
show(c("x,x", "1,2"))
show(c("x,", "1,2"))
x <- fread(path, select = "x")
print(x)
unlink(path)
