# `nargs()` in code that `eval` runs counts the three arguments of `eval`'s own call, wherever
# that call is. `delayedAssign` checks its name and both environments before it binds anything.
show <- function(expr) tryCatch(
    print(expr),
    error = function(e) cat("error:", conditionMessage(e), "|", deparse(conditionCall(e)), "\n")
)
show(eval(quote(nargs())))
f <- function() eval(quote(nargs()))
show(f())
g <- function(a, b) eval(quote(nargs()))
show(g(1, 2))
h <- function(a, b, ...) evalq(nargs())
show(h(1, 2, 3, 4))
k <- function(...) eval(quote(nargs()), list(a = 1))
show(k(1, 2))
show(local(nargs()))
show(with(list(a = 1), nargs()))
m <- function(x) nargs()
show(c(m(), m(1)))
file <- tempfile()
writeLines("print(nargs())", file)
show(source(file))
show(delayedAssign(1, 2))
show(delayedAssign(character(0), 2))
show(delayedAssign("x", 2, NULL))
show(delayedAssign("x", 2, 1))
show(delayedAssign("x", 2, assign.env = 1))
