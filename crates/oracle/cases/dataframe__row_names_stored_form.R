# Integer row names 1:n of three rows or more are stored as c(NA, n), which .row_names_info()
# reports as not automatic, while 1:2, 1L and other integers are stored as given and
# .set_row_names(n) stores c(NA, -n). Each construction and modification path keeps what those
# rules give, and dput() writes it.
show <- function(label, x) cat(label, ":", deparse(.row_names_info(x, 0L)), "|", .row_names_info(x, 1L), "|", .row_names_info(x, 2L), "\n")
show("df3", data.frame(a = 1:3))
show("df1", data.frame(a = 1))
show("df0", data.frame(a = integer(0)))
