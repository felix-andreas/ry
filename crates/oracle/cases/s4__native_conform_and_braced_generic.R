# Methods whose formals differ from the generic's, and generics whose body is a braced
# `standardGeneric()` call, defined inside a package namespace. ry's methods core conforms the
# method natively: it rewrites the formals in place when only `...` is omitted, and builds the
# `.local` wrapper otherwise.
info <- new.env(hash = TRUE, parent = baseenv())
imports <- new.env(hash = TRUE, parent = .BaseNamespaceEnv)
attr(imports, "name") <- "imports:s4conform"
ns <- new.env(hash = TRUE, parent = imports)
assign(".__NAMESPACE__.", info, envir = ns)
info$spec <- c(name = "s4conform", version = "1.0")
info$exports <- new.env(hash = TRUE, parent = baseenv())
info$imports <- list(base = TRUE)
info$path <- tempdir()
info$dynlibs <- character()
info$S3methods <- matrix(NA_character_, 0L, 4L)
assign(".packageName", "s4conform", envir = ns)
invisible(.Internal(registerNamespace("s4conform", ns)))
setClass("A", slots = c(a = "numeric"), where = ns)
setClass("B", contains = "A", where = ns)
setGeneric("g", function(object, x, ...) standardGeneric("g"), where = ns)
setMethod("g", "A", function(object, x) paste("A", x), where = ns)
setMethod("g", "B", function(object, ...) paste("B", ...length()), where = ns)
setGeneric("g2", function(object, x, ...) standardGeneric("g2"), where = ns)
setMethod("g2", "A", function(object, y, ...) paste("A2", missing(y)), where = ns)
setMethod("g2", "B", function(object, y = 5, ..., z) paste("B2", y), where = ns)
setGeneric("g3", function(object, x = 1, ..., na.rm = FALSE) standardGeneric("g3"), where = ns)
setMethod("g3", "A", function(object, x) x, where = ns)
setMethod("g3", "B", function(object, ..., na.rm) na.rm, where = ns)
setGeneric("g4", function(object, x) standardGeneric("g4"), where = ns)
setMethod("g4", "A", function(object) "A4", where = ns)
setMethod("g4", c("B", "missing"), function(object) "B4", where = ns)
setGeneric("g5", function(object, x, y, ...) standardGeneric("g5"), where = ns)
setMethod("g5", c("A", "missing"), function(object, y, ...) c(missing(y)), where = ns)
setMethod("g5", "B", function(object, ...) "B5", where = ns)
r <- tryCatch(setMethod("g5", c("A", "numeric"), function(object, y) "bad", where = ns), error = function(e) conditionMessage(e)); print(r)
for (f in c("g", "g2", "g3", "g4", "g5")) for (cl in c("A", "B")) { m <- getMethod(f, cl, optional = TRUE, where = ns); if (!is.null(m)) { cat(f, cl, "\n"); print(body(m)); print(formals(m)); print(names(attributes(m))) } }
for (cl in c("A", "B")) for (sig in list(cl, c(cl, "missing"), c(cl, "ANY", "numeric"))) { m <- getMethod("g5", sig, optional = TRUE, where = ns); if (!is.null(m)) { print(sig); print(body(m)); print(m@target) } }
g <- get("g", ns); g2 <- get("g2", ns); g3 <- get("g3", ns); g4 <- get("g4", ns); g5 <- get("g5", ns)
a <- new("A", a = 1); b <- new("B", a = 2)
print(g(a, 3)); print(g(b, 1, 2, 3)); print(tryCatch(g(a, 3, 4), error = function(e) conditionMessage(e)))
print(g2(a)); print(g2(a, 7)); print(g2(b)); print(g2(b, 9))
print(g3(a)); print(g3(a, 4)); print(g3(b)); print(g3(b, na.rm = TRUE))
print(g4(a)); print(g4(b)); print(g4(a, 1))
print(g5(a)); print(g5(a, y = 2)); print(g5(b, 1, 2)); print(g5(b))
setGeneric("h", function(object) {standardGeneric("h")}, where = ns)
setGeneric("h2", function(object, ...) {
  standardGeneric("h2")
}, where = ns)
setMethod("h", "A", function(object) "hA", where = ns)
setMethod("h2", "B", function(object, ...) "h2B", where = ns)
h <- get("h", ns); print(class(h)); print(body(h)); print(h(a)); print(get("h2", ns)(b)); print(isGeneric("h", where = ns)); print(is(h, "standardGeneric")); print(names(attributes(h)))
print(showMethods("h", where = ns))
