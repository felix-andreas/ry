set.seed(11)
M <- matrix(rnorm(300 * 6) * 1e3, 300, 6)
cm <- cor(M)
v <- cov(M)
print(sprintf("%a", cm[1:3, 1:3]))
print(sprintf("%a", v[1:3, 1:3]))
sdv <- sqrt(diag(v))
print(sprintf("%a", v[2, 1] / (sdv[2] * sdv[1])))
print(sprintf("%a", cor(M[, 1], M[, 2])))
print(sprintf("%a", cor(M[, 1:2])[2, 1]))
