# `x[i]` with positional subscripts on plain vectors, and every shape that must fall back.
x <- c(a = 1, b = 2, c = 3, d = 4)
y <- c(10L, 20L, 30L)
for (k in 1:3) {
  print(y[k])
  print(y[-k])
  print(x[k])
  print(x[-1L])
}
print(y[2.7])
print(y[0])
print(y[4])
print(y[NA_integer_])
print(y[NA_real_])
print(y[NA])
print(y[NaN])
print(y[-4])
print(y[c(TRUE, FALSE)])
print(y[c(TRUE, NA, FALSE, TRUE)])
print(x[c("b", "z")])
print(y["a"])
print(y[integer()])
print(y[c(-1, 0)])
print(tryCatch(y[c(-1, 1)], error = conditionMessage))
print(tryCatch(y[list(1)], error = conditionMessage))
print(tryCatch(y[1+2i], error = conditionMessage))
z <- 1:10
print(z[3])
print(z[-(1:8)])
s <- letters
print(s[c(26, 1)])
l <- list(1, "a", TRUE)
print(l[2])
print(l[-1])
m <- matrix(1:6, 2)
print(m[5])
print(m[2, 3])
print(m[-1, 2])
print(m[7])
f <- factor(c("u", "v", "u"))
print(f[2])
print(f[-1])
d <- as.Date("2024-01-01") + 0:2
print(d[2])
k <- structure(1:3, class = "mine")
`[.mine` <- function(x, i) "dispatched"
print(k[1])
print(unclass(k)[1])
q <- structure(c(5, 6), extra = "kept")
print(q[1])
e <- quote(f(a, b))
print(e[2])
print(NULL[1])
print(tryCatch(mean[1], error = conditionMessage))
g <- function(v, i) v[i]
print(g(y, 2L))
print(g(y, -2L))
print(g(x, "c"))
print(-1L)
print(-NA_integer_)
print(-2.5)
print(-NA_real_)
print(-NaN)
print(-TRUE)
