# count.fields() counts a line a quoted field runs over as NA, keeps counting fields across it,
# and errors when white-space separated input ends inside a quote.
f <- tempfile()
counts <- function(...) tryCatch(count.fields(f, ...), error = conditionMessage)
writeLines(c("a,\"b", "c,d", "e"), f)
print(counts(sep = ","))
print(counts())
writeLines(c("a \"b", "c d", "e"), f)
print(counts())
print(counts(sep = ","))
writeLines(c("a b", "", "c d e", "  ", "#x", "f # g"), f)
print(counts())
print(counts(blank.lines.skip = FALSE))
print(counts(sep = ",", blank.lines.skip = FALSE))
writeLines(c("a,b,", ",", "x"), f)
print(counts(sep = ","))
writeBin(as.raw(c(0x61, 0x2c, 0x62)), f)
print(counts(sep = ","))
print(counts())
writeLines(c("a,'b", "c',d", "e"), f)
print(counts(sep = ","))
writeLines(c("a 'b", "c' d", "e"), f)
print(counts())
writeLines(c("a b\"c d", "e"), f)
print(counts())
print(counts(sep = ","))
print(counts(skip = 1))
writeLines(character(), f)
print(counts())
unlink(f)
