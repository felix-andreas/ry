# unlist() of a list without names whose elements are NULL or atomic vectors without attributes
# combines them in one pass; anything named, classed or nested takes the general walk.
x <- list(1L, 2.5, NULL, TRUE, c(3L, 4L))
str(unlist(x))
str(unlist(list(1L, NA, FALSE)))
str(unlist(list("a", 1, TRUE)))
str(unlist(list(raw(2), as.raw(255))))
str(unlist(list(1i, 2L)))
str(unlist(list(raw(1), 1L)))
str(unlist(list(NULL, NULL)))
str(unlist(list()))
str(unlist(list(1:3, 4:6)))
str(unlist(list(c(a = 1), 2)))
str(unlist(list(1, list(2, 3))))
str(unlist(list(factor("a"), factor("b"))))
str(unlist(list(as.Date("2024-01-02"), 1)))
str(unlist(list(1, 2), use.names = FALSE))
str(unlist(list(1, "b"), recursive = FALSE))
l <- as.list(seq(0.5, 5, by = 0.5))
identical(unlist(l), seq(0.5, 5, by = 0.5))
