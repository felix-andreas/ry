# pmatch and charmatch: exact before partial, ambiguous prefixes, duplicates, NA and empty strings.
table <- c("mean", "median", "mode", "max", "", NA)
print(pmatch(c("mea", "med", "mo", "m", "max", "mean"), table))
print(pmatch(c("me", "me"), c("mean", "median")))
print(pmatch(c("mean", "mean"), c("mean", "mean")))
print(pmatch(c("mean", "mean"), c("mean", "mean"), duplicates.ok = TRUE))
print(pmatch(c("m", "me"), c("mean", "me"), duplicates.ok = TRUE))
print(pmatch("", c("", "a")))
print(pmatch(NA, c("NA", "x")))
print(pmatch(c("x", NA), c("a", NA)))
print(pmatch(c("a", "b"), c("abc", "bcd"), nomatch = 0L))
print(pmatch(character(0), c("a")))
print(pmatch(c("a"), character(0)))
print(pmatch(c("ab", "abc", "a"), c("abc", "abd", "a")))
print(pmatch(c("é", "ét"), c("été", "hiver")))
print(pmatch(1:3, c("1", "2", "10")))
print(charmatch(c("", "m", "med", "mean", "x"), c("mean", "median")))
print(charmatch("m", c("mean", "mean")))
print(charmatch("mean", c("mean", "mean")))
print(charmatch(c("a", NA), c("abc", NA), nomatch = -1L))
print(charmatch("ét", c("été", "étang")))
print(charmatch(character(0), "a"))
