# Bit conversions, `diag` and `unclass` at lengths on both sides of 64.
print(intToBits(c(1L, -1L, NA))[c(1:3, 32:34, 65:66, 96)])
print(packBits(intToBits(c(5L, NA, -7L)), "integer"))
print(packBits(rawToBits(as.raw(c(1, 128, 255))), "raw"))
print(packBits(as.logical(intToBits(9L)), "integer"))
print(packBits(numToBits(c(pi, -0.5, NA)), "double"))
print(numToInts(c(1, NA, Inf)))
print(rawShift(as.raw(c(1, 15, 255)), 3))
print(rawShift(as.raw(c(1, 15, 255)), -2))
print(length(intToBits(integer())))
print(packBits(raw(), "raw"))
print(tryCatch(packBits(c(NA, rep(TRUE, 7)), "raw"), error = conditionMessage))
print(tryCatch(packBits(1:7, "raw"), error = conditionMessage))
print(tryCatch(packBits(1:8, "word"), error = conditionMessage))
print(tryCatch(packBits(1:8, c("raw", "raw")), error = conditionMessage))
print(tryCatch(packBits(as.numeric(1:8), "raw"), error = conditionMessage))
print(tryCatch(rawToBits(1:3), error = conditionMessage))
print(tryCatch(numToBits(1:3), error = conditionMessage))
print(tryCatch(rawShift(as.raw(1), 9), error = conditionMessage))
