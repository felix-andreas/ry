# do.call() checks its arguments in its R code and again in its internal function, whose
# errors name the do.call() call.
show <- function(expr) tryCatch(print(expr), error = function(e)
    cat(conditionMessage(e), "|", deparse(conditionCall(e)), "\n"))
show(do.call(el, as.pairlist(list(1:3, 2))))
show(do.call(el, 1:3))
show(do.call("el", list(1:3, 2)))
show(do.call(1, list()))
show(do.call(c("a", "b"), list()))
show(do.call(el, list(1:3, 2), envir = 1))
show(do.call(el, NULL))
show(do.call("no such function", list()))
show(do.call("", list()))
show(do.call(NA_character_, list()))
show(do.call(1, 1:3, envir = 1))
show(do.call(el, 1:3, envir = NULL))
show(do.call(el, as.pairlist(list(1:3, 2)), envir = NULL))
show(do.call(el, list(1:3, 2), envir = NULL))
show(do.call(el, list(1:3, 2), envir = list(a = 1)))
show(do.call(quote(el), list(1:3, 2)))
show(do.call(function(...) ..2, list(1, quote(x), 3), quote = TRUE))
