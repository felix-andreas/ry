value <- list(a = 1:3, b = c(x = 1.5, y = NA), c = "text", d = list(TRUE, NULL), f = factor(c("u", "v", "u")))
bytes <- serialize(value, NULL)
stopifnot(is.raw(bytes))
str(unserialize(bytes))
identical(unserialize(bytes), value)
identical(unserialize(serialize(value, NULL, xdr = FALSE)), value)
ascii <- serialize(value, NULL, ascii = TRUE)
rawToChar(ascii[1:2])
identical(unserialize(ascii), value)
identical(unserialize(serialize(value, NULL, version = 2)), value)
connection <- rawConnection(raw(0), "wb")
serialize(value, connection)
written <- rawConnectionValue(connection)
close(connection)
identical(written, bytes)
connection <- rawConnection(written, "rb")
identical(unserialize(connection), value)
close(connection)
