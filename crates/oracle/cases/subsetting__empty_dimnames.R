# An empty selection along a dimension stores NULL dimnames, as in GNU R.
x <- matrix(1:36, 6, dimnames = list(letters[1:6], LETTERS[1:6]))
str(dimnames(x[-1:-6, , drop = FALSE]))
str(dimnames(x[integer(0), , drop = FALSE]))
str(rowMeans(x[-1:-6, , drop = FALSE]))
str(dimnames(x[, -1:-6, drop = FALSE]))
v <- c(a = 1, b = 2)
str(v[-1:-2])
str(v[integer(0)])
str(x[integer(0), 1])
str(x[integer(0), 1:2])
a <- array(1:8, c(2,2,2), dimnames = list(c("a","b"), NULL, c("u","v")))
str(dimnames(a[0, , , drop = FALSE]))
str(dimnames(a[0, , ]))
