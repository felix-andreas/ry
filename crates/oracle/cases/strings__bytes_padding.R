# Byte strings pad to the width of their \xNN spelling in print, format and formatC.
x <- c("abc", "\xff\xfe", "d")
Encoding(x) <- c("unknown","bytes","unknown")
print(x)
print(x, quote = FALSE)
print(c(a = x[2], b = "zz"))
formatC(x, width = 8)
formatC(x, width = -8)
format(x)
nchar(format(x))
m <- matrix(x, 1); print(m)
y <- "\xe9t\xe9"; Encoding(y) <- "bytes"; print(c(y, "long string"))
data.frame(v = x)
f <- format(x); print(Encoding(f)); print(nchar(f, "bytes"))
format(c("a\\b", "x"))
print(c("a\\b", "x"))
y <- 'q"\xff'; Encoding(y) <- "bytes"; print(c(y, "abcdefghij"), quote = FALSE)
noquote(x)
