# writeBin() to a raw vector encodes each element at its size, swapped for the other endianness.
writeBin(c(1L, -2L, NA), raw())
writeBin(c(1L, 258L), raw(), size = 2)
writeBin(c(1L, 258L), raw(), size = 1)
writeBin(c(1L, -1L), raw(), size = 8)
writeBin(c(1L, 258L), raw(), endian = "big")
writeBin(c(TRUE, FALSE, NA), raw())
writeBin(c(1.5, -2, NA, Inf), raw())
writeBin(c(1.5, -2), raw(), size = 4)
writeBin(1.5, raw(), endian = "big")
writeBin(complex(real = 1, imaginary = -1), raw())
writeBin(complex(real = 1, imaginary = -1), raw(), endian = "big")
writeBin(c("ab", NA, "", "c"), raw())
writeBin(as.raw(1:3), raw())
writeBin(numeric(), raw())
writeBin(character(), raw())
tryCatch(writeBin(list(1), raw()), error = function(e) conditionMessage(e))
tryCatch(writeBin(1.5, raw(), size = 2), error = function(e) conditionMessage(e))
f <- tempfile()
con <- file(f, "wb"); writeBin(c(1L, 2L), con); writeBin("xy", con); close(con)
readBin(f, "raw", 100)
