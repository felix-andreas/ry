# `list.files` filters names by an extended regular expression, a literal with `fixed`, either
# without regard to case, and follows a link to a directory when it descends.
root <- file.path(tempdir(), "list-files-case")
unlink(root, recursive = TRUE)
dir.create(file.path(root, "sub", "deep"), recursive = TRUE)
dir.create(file.path(root, ".hidden"))
dir.create(file.path(root, "empty"))
for (name in c("a.R", "b.r", "c.Rmd", "d.txt", "a+b.R", ".dot.R", "sub/e.R", "sub/f.txt",
               "sub/deep/g.R", ".hidden/h.R", "UPPER.TXT", "R"))
  writeLines("x", file.path(root, name))
linked <- file.symlink(file.path(root, "sub"), file.path(root, "link"))
show <- function(...) print(list.files(root, ...))

show()
show(pattern = "\\.[Rr]$")
show(pattern = "\\.[Rr]$", recursive = TRUE)
show(pattern = "\\.[Rr]$", recursive = TRUE, all.files = TRUE)
show(pattern = "^[a-c]", ignore.case = TRUE)
show(pattern = "txt", ignore.case = TRUE, recursive = TRUE)
show(pattern = "a+b", fixed = TRUE)
show(pattern = "a+b")
show(pattern = "A+B", fixed = TRUE, ignore.case = TRUE)
show(pattern = ".R", fixed = TRUE)
show(pattern = "[[:upper:]]+\\.[[:alpha:]]{3}$")
show(pattern = "^R$")
show(pattern = "e|g", recursive = TRUE, include.dirs = TRUE)
show(recursive = TRUE, include.dirs = TRUE)
show(all.files = TRUE)
show(all.files = TRUE, no.. = TRUE)
show(pattern = "^\\.", all.files = TRUE)
show(pattern = "R", all.files = TRUE)
print(sub(root, "<root>", list.files(root, pattern = "^\\.+$", all.files = TRUE, full.names = TRUE), fixed = TRUE))
show(pattern = "nothing-matches")
print(sub(root, "<root>", list.files(root, pattern = "\\.R$", full.names = TRUE, recursive = TRUE), fixed = TRUE))
print(basename(list.files(c(file.path(root, "sub"), root), pattern = "^[ef]")))
print(list.files(file.path(root, "missing"), pattern = "x"))
print(list.files(file.path(root, "empty")))
print(tryCatch(list.files(root, pattern = "(["), error = conditionMessage))
print(tryCatch(list.files(root, pattern = "a{2,1}"), error = conditionMessage))
# The same pattern again, after others, answers the same.
first <- list.files(root, pattern = "\\.[Rr]$")
for (round in 1:3) stopifnot(identical(list.files(root, pattern = "\\.[Rr]$"), first))
print(list.files(root, pattern = "\\.[RR]$", ignore.case = TRUE))
print(list.dirs(root, full.names = FALSE))
print(list.dirs(root, full.names = FALSE, recursive = FALSE))
unlink(root, recursive = TRUE)
