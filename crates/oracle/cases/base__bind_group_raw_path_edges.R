# Edge cases of cbind's recycled columns, rowsum's grouping, as.raw on integers and file.path.
print(cbind(1:6, c(1.5, 2.5), c(TRUE, FALSE, NA)))
print(cbind(a = 1:4, b = 1:2, c = 7L))
print(cbind(matrix(1:6, 3), 1:3, matrix(c(0.5, NA, 2), 3)))
print(cbind(matrix(c(TRUE, FALSE, NA, TRUE), 2), 1:2))
print(cbind(1:3, c("x", "y", "z"), 4:6))
print(cbind(numeric(0), integer(0)))
print(cbind(matrix(numeric(0), 0, 2), numeric(0)))
print(tryCatch(cbind(1:3, 1:2), warning = conditionMessage))
x <- c(1, 2, 3, 4, 5, NA)
print(rowsum(x, c(2L, 1L, 2L, NA, 1L, 3L)))
print(rowsum(x, c("b", "a", "b", NA, "a", "c")))
print(rowsum(x, c(2.5, 1, 2.5, NaN, 1, NA)))
print(rowsum(matrix(1:12, 6), c(1, 1, 2, 2, 3, 3), reorder = FALSE))
print(rowsum(c(1, 2), c(-0, 0)))
print(rowsum(1:4, factor(c("u", "v", "u", "v"))))
print(as.raw(c(0L, 1L, 255L)))
print(suppressWarnings(as.raw(c(-1L, 256L, NA, 7L))))
print(tryCatch(as.raw(c(1L, 300L)), warning = conditionMessage))
print(as.raw(c(TRUE, FALSE, NA)))
print(as.raw(structure(1:3, names = c("a", "b", "c"))))
print(file.path("a", c("b", "c"), NA))
print(file.path(c("x", "y", "z"), "f", fsep = "\\"))
print(file.path("a", character(0)))
print(file.path())
print(file.path(1, TRUE, 2.5))
print(file.path("é", "ü"))
