# dimnames<- removes only for an empty list, pads short lists, and keeps a list of NULLs; subsetting keeps it.
x <- 1; attributes(x) <- list(dim = c(1L, 1L), dimnames = list(NULL, NULL)); print(attributes(x))
y <- matrix(1); dimnames(y) <- list(NULL, NULL); print(attributes(y))
w <- matrix(1); attr(w, "dimnames") <- list(NULL, NULL); print(attributes(w))
v <- structure(1, dim = c(1L, 1L), dimnames = list(NULL, NULL)); print(attributes(v))
show <- function(e) print(tryCatch(attributes(e), error = conditionMessage))
x <- matrix(1:4, 2)
show({ y <- x; dimnames(y) <- list(character(0), c("a", "b")); y })
show({ y <- x; dimnames(y) <- list(c("r", "s")); y })
show({ y <- x; dimnames(y) <- list(); y })
show({ y <- x; dimnames(y) <- list(NULL, NULL, NULL); y })
show({ y <- x; dimnames(y) <- list(a = NULL, b = NULL); y })
show({ y <- x; dimnames(y) <- list(1:2, factor(c("u", "v"))); y })
cd <- structure(1:4, dim = c(2L, 2L), dimnames = list(NULL, NULL))
print(attributes(cd[2:1, , drop = FALSE])); print(attributes(cd[1, , drop = FALSE])); print(attributes(cd[, 1, drop = FALSE]))
print(attributes(cd[2:1, ])); print(attributes(t(cd))); print(attributes(cd + 1L))
print(attributes(rbind(cd, cd))); print(attributes(cd[2:1]))
y <- cd; y[1,1] <- 9L; print(attributes(y))
