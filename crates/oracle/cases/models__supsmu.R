# supsmu(): Friedman's super smoother, with a fixed span, cross-validated spans, the bass
# control, periodic x, tied x values, weights, and the trace of each running-lines smooth.
set.seed(1)
x <- sort(runif(60))
y <- sin(2 * pi * x) + rnorm(60, sd = 0.3)
show <- function(s) print(signif(s$y, 10))
show(supsmu(x, y))
show(supsmu(x, y, span = 0.3))
show(supsmu(x, y, bass = 5))
show(supsmu(x, y, periodic = TRUE))
show(supsmu(x, y, wt = rep(1:3, 20)))
xt <- round(x, 1)
s <- supsmu(xt, y)
print(s$x)
show(s)
show(supsmu(1:3, c(2, 1, 3)))
show(supsmu(rep(1, 4), 1:4))
show(supsmu(c(1, 2, NA, 4, 5), c(1, 3, 2, 5, 4)))
invisible(supsmu(1:10, (1:10)^2, trace = TRUE))
