directory <- tempfile()
dir.create(directory)
path <- function(name) file.path(directory, name)
jpeg(path("plot.jpg"), width = 200, height = 150, quality = 80)
plot(1:10)
invisible(dev.off())
bytes <- readBin(path("plot.jpg"), "raw", 4)
print(bytes[1:3])
postscript(path("plot.ps"))
plot(1:10, main = "two pages")
plot(10:1)
invisible(dev.off())
lines <- readLines(path("plot.ps"))
print(lines[1])
print(grep("^%%Page:", lines, value = TRUE))
print(grep("^%%Orientation", lines, value = TRUE))
setEPS()
postscript(path("plot.eps"), width = 4, height = 3)
hist(c(1, 2, 2, 3))
invisible(dev.off())
eps <- readLines(path("plot.eps"))
print(eps[1])
print(grep("^%%BoundingBox", eps, value = TRUE))
postscript(path("page%d.ps"), onefile = FALSE, paper = "special", width = 3, height = 3)
plot(1)
plot(2)
invisible(dev.off())
print(sort(list.files(directory, pattern = "^page")))
