directory <- tempfile()
dir.create(directory)
path <- function(name) file.path(directory, name)
jpeg(path("plot.jpg"), width = 200, height = 150, quality = 80)
plot(1:10)
invisible(dev.off())
bytes <- readBin(path("plot.jpg"), "raw", 4)
print(bytes[1:3])
postscript(path("plot.ps"))
plot(1:10, main = "two pages")
plot(10:1)
invisible(dev.off())
lines <- readLines(path("plot.ps"))
print(lines[1])
print(grep("^%%Page:", lines, value = TRUE))
print(grep("^%%Orientation", lines, value = TRUE))
setEPS()
postscript(path("plot.eps"), width = 4, height = 3)
hist(c(1, 2, 2, 3))
invisible(dev.off())
eps <- readLines(path("plot.eps"))
print(eps[1])
print(grep("^%%BoundingBox", eps, value = TRUE))
postscript(path("page%d.ps"), onefile = FALSE, paper = "special", width = 3, height = 3)
plot(1)
plot(2)
invisible(dev.off())
print(sort(list.files(directory, pattern = "^page")))
print(grep("^%%(DocumentMedia|Orientation)", eps, value = TRUE))
header <- function(...) {
  file <- tempfile(fileext = ".ps", tmpdir = directory)
  postscript(file, onefile = TRUE, ...)
  plot(1)
  invisible(dev.off())
  print(grep("^%%(DocumentMedia|Orientation|BoundingBox)|^%!", readLines(file), value = TRUE))
}
header(paper = "a4")
header(paper = "a4", horizontal = FALSE, width = 5, height = 5)
header(paper = "letter", horizontal = FALSE)
header(paper = "special", width = 4, height = 3)
header(paper = "a4", horizontal = TRUE)
header(paper = "special", width = 4, height = 3, horizontal = TRUE)
