# Objects serialized over a binary socket arrive one per unserialize() call, and a closed peer
# ends the stream.
port <- 41874L
server <- serverSocket(port)
client <- socketConnection("localhost", port, blocking = TRUE, open = "a+b")
peer <- socketAccept(server, blocking = TRUE, open = "a+b")
print(summary(peer)$text)
serialize(list(1, "a"), client)
serialize(2:3, client)
writeBin(42L, client)
str(unserialize(peer))
str(unserialize(peer))
print(readBin(peer, "integer", 1))
close(client)
print(tryCatch(unserialize(peer), error = conditionMessage))
print(readBin(peer, "integer", 1))
close(peer)
close(server)

# A file connection holds several objects in a row, in any format. An ASCII object that ends
# in a string leaves the newline after it unread.
path <- tempfile()
con <- file(path, "wb")
serialize(list(x = 1), con)
serialize(TRUE, con, xdr = FALSE)
serialize("ascii", con, ascii = TRUE)
serialize(3L, con, ascii = TRUE)
serialize("end", con, ascii = TRUE)
writeBin(7L, con)
close(con)
con <- file(path, "rb")
str(unserialize(con))
str(unserialize(con))
str(unserialize(con))
str(unserialize(con))
str(unserialize(con))
print(readBin(con, "raw", 8))
print(tryCatch(unserialize(con), error = conditionMessage))
close(con)
unlink(path)
