  for (size in list(NA_integer_, 1L, 2L, 3L, 4L, 8L, 16L)) {
    cat("writeBin", deparse(v), size, "\n"); t_(writeBin(v, f, size = size)); if (file.exists(f)) { show(); unlink(f) }
