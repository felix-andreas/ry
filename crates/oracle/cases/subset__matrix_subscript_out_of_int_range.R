# A double matrix or array subscript outside the integer range selects NA with a coercion warning.
h <- function(e) withCallingHandlers(e, warning = function(w) { cat("W:", conditionMessage(w), "|", deparse(conditionCall(w))[1], "\n"); invokeRestart("muffleWarning") })
m <- matrix(1:4, 2)
print(h(m[1, 1e10]))
print(h(m[1e10, ]))
print(h(m[c(1, 3e9), 2]))
print(tryCatch(h(m[1, -1e10]), error = conditionMessage))
x <- m; h(x[1, 1e10] <- 9L); print(x)
x <- m; h(x[3e9, 1] <- 9L); print(x)
z <- matrix(0i, 3, 3); h(z[3, 1e10] <- 1+2i); print(z)
a <- array(1:8, c(2, 2, 2)); print(h(a[1, 1, 1e10]))
f <- function(m) m[1, 1e10]; print(h(f(m)))
print(h(m[1, 2.9]))
print(tryCatch(m[1, 2^31 - 1], error = conditionMessage))
print(h(m[1e10]))
