# Partial sorting places the requested positions as a full sort would and leaves the rest in the
# order the selection algorithm produces, which must match GNU R's for doubles, integers, logicals,
# strings, NA and NaN, ties, and attributes; quantile() and median() are built on it.
set.seed(42)
x <- round(rnorm(40), 1)
sort(x, partial = 20)
sort(x, partial = c(5, 20, 35))
sort(c(3, NA, 1, NaN, 2, 5, 4), partial = 3)
sort(c(3, 1, 2, 5, 4, 2, 2, 9, 1, 1), partial = 4)
i <- sample(c(1:15, NA, NA), 17)
sort(i, partial = c(2, 9), na.last = TRUE)
.Internal(psort(i, 8L))
.Internal(psort(c(TRUE, FALSE, NA, TRUE, FALSE), 2L))
.Internal(psort(c("pear", "apple", "fig", "kiwi", "date"), 3L))
y <- c(a = 5, b = 3, c = 9, d = 1, e = 7)
sort(y, partial = 2)
.Internal(psort(structure(c(5, 3, 9, 1, 7), class = "foo", names = letters[1:5]), 3L))
tryCatch(.Internal(psort(x, 41)), error = conditionMessage)
quantile(x)
quantile(x, c(0.1, 0.333, 0.9), type = 7)
quantile(i, 0.5, na.rm = TRUE, type = 1)
quantile(c(x, NA), na.rm = TRUE, names = FALSE)
median(x)
median(i, na.rm = TRUE)
median(c(1L, 2L, 4L, 8L))
