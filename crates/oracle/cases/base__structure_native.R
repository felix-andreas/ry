# structure() sets plain attributes and classes, and validates the special ones.
print(structure(1:3, class = "myclass") |> unclass())
x <- structure(list(a = 1), class = c("record", "list"), id = 7L); print(attributes(x))
print(attributes(structure(c(a = 1, b = 2), note = "n", class = "tagged")))
print(structure(1:6, dim = 2:3)); print(structure(1:4, .Dim = c(2L, 2L), .Dimnames = list(c("a", "b"), NULL)))
print(structure(1:2, names = c("p", "q"))); print(structure(c(1, 2), class = "factor", levels = c("u", "v")))
print(tryCatch(structure(1:3, dim = 2L), error = conditionMessage))
print(tryCatch(structure(1:3, class = 1), error = conditionMessage))
print(tryCatch({ x <- 1:2; attr(x, "class") <- 2; x }, error = conditionMessage))
print(tryCatch({ x <- c(1, 2); attributes(x) <- list(class = "factor"); x }, error = conditionMessage))
print(structure(1:3)); print(structure("a", class = character(0)) |> attributes())
y <- 1:3; z <- structure(y, flag = TRUE); print(attributes(y)); print(attributes(z))
print(attributes(structure(structure(1, a = 1, b = 2), a = 3)))
print(attributes(structure(1, a = 1, a = 2)))
print(attributes(structure(1, flag = NULL, keep = 1)))
print(tryCatch(structure(1, 2), error = conditionMessage))
f <- function() structure(1, class = { cat("class\n"); "c1" }, extra = { cat("extra\n"); 2 })
print(attributes(f()))
print(attributes(structure(1:2, comment = "hidden", tsp = c(1, 2, 1))))
print(attributes(structure(data.frame(a = 1:2), row.names = c("r1", "r2"))))
print(withVisible(structure(1, a = 1))$visible)
