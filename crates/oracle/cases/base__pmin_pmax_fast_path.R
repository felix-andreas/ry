# pmin() and pmax() on the shapes their native prologues cover, next to the ones they hand to the
# R bodies: types, na.rm, recycling and its warning, the first argument's attributes, zero-length
# and NULL arguments, classed arguments, and errors.
show <- function(x) { print(x); str(x); print(attributes(x)) }
caught <- function(expr) withCallingHandlers(
  tryCatch(expr, error = function(e) cat("error:", conditionMessage(e), "| call:", deparse(conditionCall(e)), "\n")),
  warning = function(w) {
    cat("warning:", conditionMessage(w), "| call:", deparse(conditionCall(w)), "\n")
    invokeRestart("muffleWarning")
  }
)
set.seed(1)
m <- matrix(round(rnorm(12), 3), 4, dimnames = list(letters[1:4], paste0("c", 1:3)))
for (f in list(pmin, pmax)) {
  show(f(3L, 2L))
  show(f(c(1L, 5L, NA), 3))
  show(f(c(1L, 5L, NA), 3, na.rm = TRUE))
  show(f(c(TRUE, FALSE, NA), c(FALSE, FALSE, TRUE)))
  show(f(TRUE, 0.5))
  show(f(c(NA, NaN, 1), c(NaN, NA, NA)))
  show(f(c(NA, NaN, 1), c(NaN, NA, NA), na.rm = TRUE))
  show(f(c("b", "a", NA), c("a", "c", "b")))
  show(f(c("b", "a", NA), "a", na.rm = TRUE))
  show(f(1:6, 2:3))
  show(f(m, 0))
  show(f(0, m))
  show(f(m, t(m)[1:4]))
  show(f(m, 1:24))
  show(f(m[, 1:2, drop = FALSE] * 1.1 + m[, 2:3], 0.3))
  show(f(m[, 1:2], m[, 3]))
  show(f(matrix(1:6, 2), 3L))
  show(f(matrix(1:6, 2, dimnames = list(c("r1", "r2"), NULL)), 3L))
  show(f(array(1:8, c(2, 2, 2), dimnames = list(NULL, c("x", "y"), c("p", "q"))), 4))
  show(f(c(a = 1, b = 5, c = 3), 2))
  show(f(c(a = 1, b = 5), 1:4))
  show(f(2, c(a = 1, b = 5)))
  show(f(structure(1:3, foo = "bar", baz = 1:2), 2L))
  show(f(structure(1:3, comment = "note"), 2L))
  show(f(structure(c(a = 1, b = 2), extra = TRUE), c(0, 3)))
  show(f(numeric(0), 1))
  show(f(1, numeric(0)))
  show(f(matrix(numeric(0), 0, 3), 1))
  show(f(NULL, 1:3))
  show(f(1:3, NULL))
  show(f(c(1, NA), NULL, na.rm = TRUE))
  caught(show(f(1:3, 1:2)))
  caught(show(f(m, 1:5)))
  caught(f())
  caught(f(1, na.rm = NA))
  caught(f(1, na.rm = "yes"))
  caught(f(list(1, 2), 1))
  caught(f(1+2i, 1))
  caught(f(as.raw(1), as.raw(2)))
  show(f(as.Date("2024-03-15") + 0:2, as.Date("2024-03-16")))
  show(f(factor(c("a", "b"), ordered = TRUE), "a"))
  show(f(ts(1:4, start = 2000), 2))
  show(f(structure(1:4, tsp = c(1, 4, 1)), 2L))
  show(f(as.POSIXct("2024-03-15", tz = "UTC") + c(0, 86400), as.POSIXct("2024-03-15 12:00", tz = "UTC")))
  show(f(structure(c(1, 5), class = "myNumber"), 3))
  show(f(data.frame(a = 1:3)$a, 2L))
  show(f(x = 1:3, 2))
  show(f(1:3, 2, na.rm = FALSE))
}
order <- character(0)
note <- function(label, value) { order <<- c(order, label); value }
show(pmax(note("a", 1:3), note("b", 2), na.rm = note("na.rm", FALSE)))
show(pmin(note("c", m), note("d", 0), na.rm = note("na.rm", TRUE)))
print(order)
