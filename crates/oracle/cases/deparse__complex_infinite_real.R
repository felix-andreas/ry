# A complex value with an infinite real part and a finite imaginary part deparses as `Inf+0i`,
# which parses back; a NaN real part or a non-finite imaginary part needs `complex(...)`.
v <- c(0+0i, complex(real = Inf, imaginary = 0))
print(deparse(v))
print(deparse(call("f", v)))
print(deparse(call("f", value = v)))
dput(v)
z <- complex(real = c(Inf, -Inf, Inf, NaN, NA, 1.5), imaginary = c(1, -2.5, NaN, 0, 3, -Inf))
dput(z)
dput(z, control = "digits17")
dput(z, control = "hexNumeric")
dput(z[1:2], control = "S_compatible")
print(deparse(complex(real = Inf, imaginary = 0)))
print(deparse(call("f", c(NA, complex(real = Inf, imaginary = 0)))))
print(deparse(call("-", complex(real = -Inf, imaginary = 1))))
print(deparse(call("^", complex(real = Inf, imaginary = 1), 2)))
print(deparse(z[1] * 1:3))
print(eval(parse(text = deparse(z[1:2]))[[1]]))
