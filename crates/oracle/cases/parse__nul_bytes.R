# A NUL byte in parsed text.
f <- tempfile()
show <- function(expr) {
  result <- withVisible(tryCatch(
    withCallingHandlers(expr, warning = function(w) {
      cat("warning:", gsub(f, "FILE", conditionMessage(w), fixed = TRUE), "\n")
      invokeRestart("muffleWarning")
    }),
    error = function(e) {
      cat("error:", class(e)[1], gsub(f, "FILE", conditionMessage(e), fixed = TRUE), "\n")
      invisible(NULL)
    }
  ))
  if (result$visible) print(result$value)
}
bytes <- function(...) writeBin(as.raw(c(...)), f)
# A NUL after a number ends the file for the grammar
bytes(0x61, 0x20, 0x3c, 0x2d, 0x20, 0x31, 0x00, 0x32, 0x0a, 0x62)
show(parse(f))
show(source(f, echo = TRUE))
# At the start of the file
bytes(0x00, 0x61, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# Inside a string
bytes(0x22, 0x61, 0x00, 0x62, 0x22, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# Inside a comment
bytes(0x23, 0x61, 0x00, 0x62, 0x0a, 0x31, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# After a symbol on a later line
bytes(0x31, 0x20, 0x2b, 0x0a, 0x61, 0x62, 0x00, 0x62, 0x60, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# After a grammar error
bytes(0x31, 0x20, 0x2b, 0x0a, 0x29, 0x62, 0x00, 0x62, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# Inside a %% operator
bytes(0x31, 0x20, 0x2b, 0x0a, 0x25, 0x62, 0x00, 0x62, 0x25, 0x33, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# Inside a raw string
bytes(0x78, 0x0a, 0x79, 0x0a, 0x72, 0x22, 0x28, 0x62, 0x00, 0x62, 0x29, 0x22, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# A name ends at its NUL: an operator, a backquoted name, an argument name
bytes(0x31, 0x20, 0x25, 0x62, 0x00, 0x62, 0x25, 0x20, 0x33, 0x0a)
show(parse(f))
show(as.character(parse(f)[[1]][[1]]))
bytes(0x60, 0x61, 0x00, 0x62, 0x60, 0x20, 0x3c, 0x2d, 0x20, 0x32, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
bytes(0x63, 0x28, 0x60, 0x61, 0x00, 0x62, 0x60, 0x20, 0x3d, 0x20, 0x31, 0x29, 0x24, 0x60, 0x61, 0x00, 0x60, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# The string as the message shows it: a tab and a quote before the NUL
bytes(0x27, 0x5c, 0x74, 0x22, 0x00, 0x62, 0x27, 0x0a)
show(parse(f))
# As the last byte
bytes(0x31, 0x0a, 0x00)
show(parse(f))
show(source(f, echo = TRUE))
# No expression before it runs
bytes(0x7a, 0x7a, 0x7a, 0x20, 0x3c, 0x2d, 0x20, 0x36, 0x0a, 0x7a, 0x7a, 0x7a, 0x20, 0x2b, 0x00, 0x20, 0x31, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# The escape
bytes(0x27, 0x61, 0x5c, 0x78, 0x30, 0x30, 0x62, 0x27, 0x0a)
show(parse(f))
show(source(f, echo = TRUE))
# The column counts a tab to the next multiple of 8
bytes(0x66, 0x28, 0x31, 0x2c, 0x0a, 0x09, 0x32, 0x2c, 0x00, 0x20, 0x33, 0x29, 0x0a)
