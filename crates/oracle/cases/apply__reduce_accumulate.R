# `Reduce(..., accumulate = TRUE)` in every direction, with and without `init`, and the
# results that keep a list or delete slots.
add <- function(a, b) a + b
print(Reduce(add, 1:5, accumulate = TRUE))
print(Reduce(add, 1:5, accumulate = TRUE, right = TRUE))
print(Reduce(add, 1:5, 100, accumulate = TRUE))
print(Reduce(add, 1:5, 100, accumulate = TRUE, right = TRUE))
print(Reduce(`+`, list(1, 2, 3), accumulate = TRUE))
print(Reduce(function(a, b) paste(a, b), letters[1:4], accumulate = TRUE))
print(Reduce(function(a, b) c(a, b), 1:4, accumulate = TRUE))
print(Reduce(function(a, b) c(a, b), 1:4, accumulate = TRUE, right = TRUE))
print(Reduce(function(a, b) list(a, b), 1:3, accumulate = TRUE))
print(Reduce(function(a, b) NULL, 1:4, accumulate = TRUE))
print(Reduce(function(a, b) if (b == 3) NULL else b, 1:5, accumulate = TRUE))
print(Reduce(function(a, b) if (b == 3) NULL else b, 1:5, 0, accumulate = TRUE))
print(Reduce(function(a, b) if (b == 2) NULL else b, 1:5, accumulate = TRUE, right = TRUE))
print(Reduce(add, 7, accumulate = TRUE))
print(Reduce(add, 7, 1, accumulate = TRUE))
print(Reduce(add, c(a = 1, b = 2, c = 3), accumulate = TRUE))
print(Reduce(function(a, b) c(x = a + b), 1:3, accumulate = TRUE))
print(Reduce(function(a, b) factor(b), letters[1:3], accumulate = TRUE))
print(Reduce(function(a, b) as.Date("2024-01-01") + b, 1:3, 0, accumulate = TRUE))
print(Reduce(function(a, b) quote(x), 1:3, accumulate = TRUE))
print(Reduce(add, list(), accumulate = TRUE))
print(Reduce(add, list(), 5, accumulate = TRUE))
seen <- character()
invisible(Reduce(function(a, b) { seen <<- c(seen, paste(a, b)); a * b }, 1:4, accumulate = TRUE))
print(seen)
print(tryCatch(Reduce(function(a, b) stop("at ", b), 1:3, accumulate = TRUE), error = conditionMessage))
print(tryCatch(Reduce(add, 1:3, accumulate = NA), error = conditionMessage))
