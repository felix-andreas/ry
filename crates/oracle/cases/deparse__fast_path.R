show(g(a + b))
show(g(function(z) z))
e <- new.env()
show(class(deparse(e)))
show(deparse(quote(x[[1]]$y@z)))
show(deparse(quote(if (a) b else c)))
show(deparse(-1L))
show(deparse(c(TRUE, NA)))
show(deparse(3+2i))
