# deparse() with its default backtick and control, and .deparseOpts() with explicit options,
# including the errors and warnings the R bodies report.
show <- function(x) print(x)
show(deparse(quote(f(x, y = 2))))
show(deparse(quote((a + b) * c)))
show(deparse(quote(`a b` + 1)))
show(deparse(as.name("a b")))
show(deparse(as.name("a b"), backtick = TRUE))
show(deparse(quote(`a b` + 1), backtick = FALSE))
show(deparse(function(x) x + 1))
show(deparse(sum))
show(deparse(`if`))
show(deparse(expression(a + 1, `b c`)))
show(deparse(1:3))
show(deparse(c(1.5, NA, 3)))
show(deparse(c(a = 1L, b = NA)))
show(deparse(list(x = 1, "y")))
show(deparse(factor(c("u", "v"))))
show(deparse(NULL))
show(deparse("text \"quoted\""))
show(deparse(1/3, control = "digits17"))
show(deparse(1/3, control = "hexNumeric"))
show(deparse(c(a = 1L), control = NULL))
show(deparse(c(a = 1L), control = character()))
show(deparse(c(a = 1L), control = "all"))
show(deparse(c(a = 1L), control = c("all", "hexNumeric")))
show(deparse(c(a = 1L), control = "exact"))
show(deparse(c(a = 1L), control = c("exact", "keepNA")))
show(deparse(c(a = 1L), control = "keepInt"))
show(deparse(c(a = 1L), control = c("keepInteger", "showAttributes")))
show(deparse(structure(1:2, class = "k"), control = "showAttributes"))
show(tryCatch(deparse(1, control = "nonsense"), error = conditionMessage))
show(tryCatch(deparse(1, control = c("nonsense", "other")), error = conditionMessage))
show(tryCatch(deparse(1, control = c("keepNA", "keepNA")), error = conditionMessage))
show(tryCatch(deparse(1, control = c("all", "exact")), error = conditionMessage))
show(tryCatch(deparse(1, control = c("hexNumeric", "digits17")), error = conditionMessage))
show(tryCatch(deparse(1, control = NA_character_), error = conditionMessage))
show(tryCatch(deparse(1, control = 2), error = conditionMessage))
show(.deparseOpts(c("keepNA", "keepInteger", "niceNames", "showAttributes")))
show(.deparseOpts("all"))
show(.deparseOpts(c("all", "hexNumeric")))
show(.deparseOpts("exact"))
show(.deparseOpts(NULL))
show(.deparseOpts(c(opt = "keepNA")))
long <- quote(some_function(argument_one = 1, argument_two = 2, argument_three = 3, argument_four = 4))
show(deparse(long))
show(deparse(long, width.cutoff = 20L))
show(deparse(long, width.cutoff = 500L))
show(deparse(long, nlines = 1L))
f <- function() deparse(long, width.cutoff = 5L)
show(withCallingHandlers(f(), warning = function(w) {
  print(conditionCall(w))
  invokeRestart("muffleWarning")
}))
show(deparse1(quote(g(1, 2))))
show(deparse1(long, collapse = " "))
dput(list(a = 1:2, b = "x"))
dput(quote(h(`x y`)))
