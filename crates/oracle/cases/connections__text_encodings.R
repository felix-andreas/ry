# A file connection with an encoding re-encodes text on its way in and out: what a character
# the encoding cannot hold does to the output, byte order marks, the marks of the strings read,
# compressed files, and an encoding that cannot convert.
f <- tempfile()
show <- function() print(readBin(f, "raw", 200))
w <- function(expr) withCallingHandlers(expr, warning = function(w) { cat("warning:", gsub(f, "FILE", conditionMessage(w), fixed = TRUE), "\n"); invokeRestart("muffleWarning") })
con <- file(f, "w", encoding = "latin1"); w(writeLines(c("aä", "x€y", "z"), con)); close(con); show()
con <- file(f, "w", encoding = "latin1"); w(writeLines(c("aä", "b"), con, useBytes = TRUE)); close(con); show()
con <- file(f, "w", encoding = "UTF-16"); w(writeLines(c("a", "b"), con)); close(con); show()
con <- file(f, "w", encoding = "UTF-16LE"); w(writeLines(c("aä"), con)); close(con); show()
con <- file(f, "w", encoding = "UTF-8"); w(writeLines(c("a\xffb", "c"), con)); close(con); show()
con <- file(f, "w", encoding = "latin1"); w(print(c("aä", "b"))); sink(con); w(print(c("aä", "b"))); sink(); close(con); show()
con <- file(f, "wb", encoding = "latin1"); w(writeLines(c("aä"), con)); close(con); show()
con <- file(f, encoding = "latin1"); w(writeLines(c("aä"), con)); close(con); show()
con <- file(f, encoding = "latin1"); w(cat("aä\n", file = con)); close(con); show()
w(cat("aä\n", file = f, fileEncoding = "latin1")); show()
w(write.table(data.frame(a = "aä"), f, fileEncoding = "latin1")); show()
w(writeLines(enc2native("aä"), f)); show()
con <- file(f, "w", encoding = "latin1"); w(writeLines(iconv("aä", "UTF-8", "latin1"), con)); close(con); show()
con <- file(f, "w", encoding = "latin1"); w(writeChar("aä", con)); w(writeBin("aä", con)); close(con); show()
writeBin(c(charToRaw("﻿aä\nb\n")), f)
con <- file(f, encoding = "UTF-8-BOM"); x <- readLines(con); close(con); print(x); print(Encoding(x))
con <- file(f, "r", encoding = "UTF-8-BOM"); x <- readLines(con); close(con); print(x); print(Encoding(x))
con <- file(f, encoding = "UTF-8"); x <- readLines(con); close(con); print(x); print(Encoding(x)); print(charToRaw(x[1]))
x <- readLines(f); print(charToRaw(x[1]))
