writeBin(as.raw(c(0x61, 0, 0xe4, 0, 0x0a, 0, 0x62, 0)), f)
for (e in c("UTF-16LE", "UTF-16")) { con <- file(f, encoding = e); x <- w(readLines(con)); close(con); print(x); print(Encoding(x)) }
