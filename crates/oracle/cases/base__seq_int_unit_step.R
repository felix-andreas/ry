# seq.int(from, to, by) with a step of one or minus one is `from:to`: whole endpoints in integer
# range give an integer vector whatever the types of the arguments.
str(seq.int(19723, 19740, by = 1))
str(seq.int(19723L, 19740L, by = 1))
str(seq.int(10, 1, by = -1))
str(seq.int(10L, 1L, by = -1))
str(seq.int(1, 3.5, by = 1))
str(seq.int(1.5, 10, by = 1))
str(seq.int(3e9, 3e9 + 2, by = 1))
str(seq.int(TRUE, 5, by = 1))
str(seq.int(1, 5, by = TRUE))
str(seq.int(1, 5, by = 1+0i))
str(seq.int(to = 5, by = 1))
str(seq.int(1, 1, by = 1))
str(seq.int(2, 8, by = 2L))
str(seq.int(2L, 8L, by = 2))
str(seq(1, 5, by = 1))
str(unclass(seq(as.Date("2024-01-01"), as.Date("2024-01-18"), by = "day")))
tryCatch(seq.int(10, 1, by = 1), error = function(e) print(conditionMessage(e)))
tryCatch(seq.int(1, 10, by = -1), error = function(e) print(conditionMessage(e)))
# Equal endpoints return `from` itself, whatever `by` is.
str(seq.int(1L, 1L, by = 1))
str(seq.int(1L, 1L, by = 0.5))
str(seq.int(2L, 2L, by = -1))
str(seq.int(TRUE, 1L, by = 1))
str(seq.int(c(a = 1L), 1L, by = 1))
str(seq.int(to = 1L, by = 0.5))
str(seq.int(1L, 1L, by = 0))
