# Raw vectors cannot be ordered or sorted, except as a later key of a radix order.
r <- as.raw(c(3, 1, 2))
show <- function(expr) print(tryCatch(expr, error = function(e) conditionMessage(e)))
show(sort(r))
show(order(r))
show(order(r, method = "radix"))
show(order(r, method = "shell"))
show(sort(r, method = "radix"))
show(xtfrm(r))
show(rank(r))
show(.Internal(radixsort(TRUE, FALSE, FALSE, TRUE, r)))
show(order(1:3, r, method = "radix"))
show(order(c(1, 1, 1), r, method = "radix"))
show(order(c(2, 1, 2), r))
