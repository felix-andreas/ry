# Integer `%/%` floors without a libm call, `!` runs one loop per type and `which` counts
# before it fills; all keep GNU R's NA rules, recycling and attributes.
big <- .Machine$integer.max
a <- c(7L, -7L, 7L, -7L, 0L, NA, 5L, big, -big, big, -big, 1L, -1L)
b <- c(2L, 2L, -2L, -2L, 3L, 1L, NA, 1L, 1L, -1L, -1L, big, big)
print(a %/% b)
print(a %% b)
print(c(5L, -5L) %/% 0L)
print(1:20 %/% c(3L, -3L, 7L, -7L))
print(big %/% c(1L, 2L, 3L, big, -big, -2L, -3L))
x <- setNames(c(-9L, -1L, 0L, 1L, 9L), letters[1:5])
print(x %/% 4L)
m <- matrix(-6:5, 3)
print(m %/% 5L)
print(identical(as.integer(floor(as.double(-100:100) / 7)), -100:100 %/% 7L))
print(!c(TRUE, FALSE, NA))
print(!c(0L, 1L, -3L, NA))
print(!c(0, -0, 2.5, NA, NaN, Inf))
print(!c(0+0i, 1i, NA))
print(!setNames(c(0L, 2L), c("p", "q")))
print(!matrix(c(0, 1, NA, 3), 2, dimnames = list(c("r1", "r2"), c("c1", "c2"))))
print(!structure(c(1L, 0L), class = "myclass"))
print(!integer(0))
print(!numeric(0))
print(which(c(FALSE, TRUE, NA, TRUE, FALSE)))
print(which(c(a = TRUE, b = FALSE, c = TRUE, d = NA)))
print(which(logical(0)))
print(which(c(FALSE, NA)))
print(which(rep(c(TRUE, FALSE, FALSE), 7)))
