# `round(x, digits)` over whole double vectors: ties to even at every digit count, NA and NaN,
# signed zeros, infinities, negative and huge digit counts, integer and logical operands, and
# attributes kept only when the operand has them.
x <- c(0.5, 1.5, 2.5, -0.5, -2.5, 0.125, 0.375, 2.675, 1.005, -0, 0, NA, NaN, Inf, -Inf, 1e300, 123456.789)
print(round(x))
print(round(x, 1))
print(round(x, 2))
print(round(x, -1))
print(round(x, -2))
print(round(x, 15))
print(round(x, 400))
print(round(x, -400))
print(round(x, 2.6))
print(round(x, NA))
print(1 / round(c(-0.4, -0, 0.4)))
print(1 / round(c(-0.04, -0), 1))
print(round(1:5, 1))
print(round(1:5, -1))
print(round(c(TRUE, NA, FALSE)))
print(round(c(a = 1.25, b = 2.35), 1))
m <- matrix(c(1.234, 5.678, 9.1011, 2.345), 2, dimnames = list(c("r1", "r2"), NULL))
print(round(m, 1))
print(attributes(round(structure(c(1.26, 2.5), foo = "bar"), 1)))
print(round(structure(c(1.26, 3.5), class = "money"), 1))
round.money <- function(x, digits = 0, ...) "money method"
print(round(structure(c(1.26, 3.5), class = "money"), 1))
print(round(c(1.26, 3.5), digits = 1))
print(round(digits = 1, c(1.26, 3.5)))
print(tryCatch(round(c(1.5, 2), "a"), error = conditionMessage))
print(round(c(1.5, 2), c(0, 1)))
print(round(numeric(0), 2))
y <- c(1.444, 2.555)
z <- round(y, 1)
print(y)
