# split() by a factor: every element kind, unused levels, NA keys dropped, recycling, names.
f <- factor(c("b", NA, "a", "b", "c", "a"), levels = c("a", "b", "c", "unused"))
print(split(1:6, f))
print(split(c(1.5, NA, NaN, -0, Inf, 2), f))
print(split(c("u", "v", NA, "x", "y", "z"), f))
print(split(c(TRUE, FALSE, NA, TRUE, TRUE, FALSE), f))
print(split(as.complex(1:6), f))
print(split(as.raw(1:6), f))
str(split(list(1, "a", NULL, 2:3, list(4), NA), f))
print(split(c(one = 1, two = 2, three = 3, four = 4, five = 5, six = 6), f))
print(split(1:6, f, drop = TRUE))
print(split(1:12, factor(c("p", "q", "p"))))
print(tryCatch(split(1:7, factor(c("p", "q"))), warning = conditionMessage))
print(split(integer(0), factor(character(0), levels = c("a", "b"))))
print(split(1:4, factor(c(NA, NA, NA, NA), levels = "a")))
print(split(1:6, list(c("x", "y", "x", "y", "x", "y"), c(1, 1, 2, 2, 1, 1))))
print(split(data.frame(a = 1:4, b = letters[1:4]), c(1, 2, 1, 2)))
print(unsplit(split(c(5, 3, 8, 1), c("a", "b", "a", "b")), c("a", "b", "a", "b")))
g <- c("north", "south", "east", "west")[1:100003 %% 4L + 1L]
