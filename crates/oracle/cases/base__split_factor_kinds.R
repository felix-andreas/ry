pieces <- split(v, g)
print(names(pieces)); print(lengths(pieces)); print(vapply(pieces, sum, 0))
print(tapply(v, g, sum))
print(tapply(1:10, factor(rep(c("a", NA), 5), levels = c("a", "z")), sum))
