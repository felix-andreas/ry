# formatC() and pmax() on the cases their native prologues cover, next to the ones they hand to
# the R bodies: other modes, marks and attributes, warnings and errors.
show <- function(x) print(x)
caught <- function(expr) withCallingHandlers(
  tryCatch(expr, error = function(e) cat("error:", conditionMessage(e), "\n")),
  warning = function(w) {
    cat("warning:", conditionMessage(w), "| call:", deparse(conditionCall(w)), "\n")
    invokeRestart("muffleWarning")
  }
)
ints <- c(0L, 7L, -42L, 123456L, NA, .Machine$integer.max)
dbls <- c(0, 1.5, -2.25, 1234567.891, NA, NaN, Inf, -Inf, 1e-10, 3e15)
for (f in c("d", "f", "e", "E", "g", "G", "fg")) {
  show(formatC(ints, format = f))
  show(formatC(dbls, format = f))
}
show(formatC(ints))
show(formatC(dbls))
for (w in list(NULL, 0L, 1L, 8L, -8L, 12)) {
  show(formatC(dbls, width = w, digits = 3L, format = "f"))
  show(formatC(ints, width = w))
}
for (fl in c("", "0", "-", "+", " ", "#", "0+", "-0", "I", "#0")) {
  show(formatC(c(3.14159, -2, NA, Inf), width = 10L, digits = 2L, format = "f", flag = fl))
  show(formatC(c(42L, -7L, NA), width = 6L, flag = fl))
  show(formatC(c(0.000123, 1234.5), format = "g", flag = fl))
  show(formatC(c(0, 1.5, 100), format = "fg", digits = 3L, flag = fl))
}
for (d in list(NULL, 0L, 1L, 6L, 15L, -1L, 2.0)) {
  show(formatC(pi * 1000, digits = d, format = "f"))
  show(formatC(pi * 1000, digits = d, format = "e"))
  show(formatC(pi * 1000, digits = d))
}
show(formatC(1:12, width = 6L, flag = "0"))
show(formatC(seq_len(5), width = 3L))
show(formatC(c(2.7, -2.7, NaN, NA), format = "d"))
show(formatC(1e5, format = "d", big.mark = ","))
show(formatC(integer()))
show(formatC(numeric(), format = "f"))
show(formatC(double(), big.mark = ","))
for (bm in c(",", "'", " ", "_", ",,")) {
  show(formatC(c(1234567.891, -1234.5, 999, 0, NA, -Inf), format = "f", digits = 2L, big.mark = bm))
  show(formatC(c(123456789L, -1000L, 12L, NA), big.mark = bm))
}
show(formatC(c(1234567, 12345678), format = "d", big.mark = ",", width = 12L))
show(formatC(c(1234567, 12345678), format = "d", big.mark = ",", width = 12L, flag = "0"))
show(formatC(c(1234567, 12345678), format = "d", big.mark = ",", width = 12L, flag = "-"))
show(formatC(c(1234567.5, 1.5), format = "f", digits = 1L, big.mark = ",", preserve.width = "none", width = 12L))
show(formatC(c(1234567.5, 1.5), format = "f", digits = 1L, big.mark = ",", preserve.width = "common", width = 12L))
show(formatC(1234567.891, format = "f", digits = 2L, big.mark = ",", big.interval = 2L))
show(formatC(123456789, format = "fg", digits = 12L, big.mark = ","))
show(formatC(1e10, format = "e", big.mark = ","))
show(formatC(1e10, format = "g", digits = 12L, big.mark = ","))
show(formatC(12345, format = "f", digits = 0L, flag = "#", big.mark = ","))
show(formatC(3.14159, format = "f", digits = 6L, small.mark = " "))
show(formatC(3.5, decimal.mark = ","))
show(formatC(c(1, 0, 2), zero.print = "-"))
show(formatC(c(1.50, 2.25), format = "f", digits = 4L, drop0trailing = TRUE))
show(formatC(c(a = 1.5, b = 2), format = "f"))
show(formatC(matrix(1:4, 2), width = 3L))
show(formatC(factor(c("u", "v"))))
caught(formatC(TRUE))
show(formatC(c("a", "bb"), width = 4L))
show(formatC(c("a", "bb"), width = -4L))
show(formatC(3.5, format = "s"))
show(formatC(3L, mode = "double", format = "f"))
show(formatC(3.5, mode = "integer"))
caught(formatC(2+3i))
caught(formatC(1, flag = "x"))
caught(formatC(1, flag = c("0", "-")))
caught(formatC(1, format = "q"))
caught(formatC(1, mode = "list"))
