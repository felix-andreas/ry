caught(formatC(1, format = "f", digits = NA_integer_))
digits_limit <- ceiling(-(.Machine$double.neg.ulp.digits + .Machine$double.min.exp) / log2(10))
show(digits_limit)
show(nchar(formatC(1, digits = digits_limit, format = "f")))
caught(formatC(1, digits = digits_limit + 1L, format = "f"))
show(formatC(0.1 + 0.2, digits = 50L, format = "g"))
caught(formatC(1, digits = 51L, format = "g"))
