# Grid's unit conversions, viewport tree and grob queries on a pdf device, whose Helvetica
# metrics ry's engine reproduces.
library(grid)
pdf(file.path(tempdir(), "units.pdf"), width = 7, height = 5)
grid.newpage()
convertWidth(unit(1, "npc"), "inches")
convertHeight(unit(1, "npc"), "cm")
convertUnit(unit(1, "lines"), "points")
convertWidth(stringWidth("hello world"), "inches")
convertHeight(stringHeight("hello"), "points")
convertWidth(unit(1, "strwidth", "wide text"), "mm")
convertX(unit(0.25, "npc") + unit(1, "inches"), "native")
pushViewport(viewport(x = 0.25, width = 0.5, xscale = c(-1, 1), name = "left"))
convertX(unit(0, "native"), "npc")
convertX(unit(1, "inches"), "native")
current.vpPath()
round(current.transform(), 4)
pushViewport(viewport(angle = 30, name = "turned"))
round(current.rotation(), 6)
upViewport(0)
current.vpTree()
downViewport("turned")
current.vpPath()
upViewport(0)
grid.rect(name = "box", width = 0.5, gp = gpar(col = "blue"))
grid.text("label", name = "lab", x = 0.2)
grid.ls()
convertWidth(grobWidth("box"), "inches")
convertX(grobX("lab", "west"), "inches")
grid.edit("lab", label = "a longer label")
convertWidth(grobWidth(grid.get("lab")), "inches")
grid.remove("box")
grid.ls()
tree <- gTree(children = gList(rectGrob(name = "r"), circleGrob(name = "c")), name = "tree")
grid.draw(tree)
grid.ls(recursive = TRUE)
invisible(dev.off())
