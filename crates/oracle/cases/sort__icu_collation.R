# In a UTF-8 locale other than C, GNU R collates strings with ICU's collator for the collation
# locale, which is the CLDR root collation under C.UTF-8. Code points show strings whose glyphs
# look alike. Ignorable characters (U+FEFF, U+00AD, U+200B, ASCII controls) do not count, an
# invalid UTF-8 byte reads as U+FFFD, and strings the collator calls equal are ties: order and
# rank keep them tied, and sort places them by its shell sort.
codes <- function(x) vapply(x, function(s) paste(utf8ToInt(s), collapse = " "), "", USE.NAMES = FALSE)
show <- function(x) print(codes(x))
show(sort(c("back", "\ufeffbom", "semi", "a\u00adb", "ab", "a\u200bb", "x", "\u00ad")))
show(sort(c("b", "a\001", "a", "a\tb", "a b", "\001", "a\nb")))
order(c("\u00df", "Z", "z", "ss", "a", "B"))
sort(c("\u00df", "Z", "z", "ss", "a", "B", "SS", "sz"))
order(c("e", "E", "\u00e9", "\u00c9", "\u00e8", "\u00ea", "f", "ea", "\u00e9a"))
sort(c("a", "B", "b", "A", "a b", "ab", "a-b", "a_b", "a.b", "10", "9", "1.5", "-1", "$5", "#x", "~", "(", "[", "{", "@", "&"))
show(sort(c("\U1F600", "\u4e2d", "\u6587", "\u0436", "\u0416", "\u03b1", "\u0391", "\u03c9", "z", "1", "\U1F34E", "\u3042", "\uac00")))
