# icuSetCollate sets the collator's attributes until the collation locale changes. GNU R's
# attribute table spells "default" and the strength values with a trailing space, so plain
# strength = "primary" is ignored.
capabilities("ICU")
icuGetCollate()
y <- c("a", "B", "b", "A", "a b", "ab", "a-b", "10", "9", "e", "E")
icuSetCollate(case_first = "upper"); sort(y)
icuSetCollate(alternate_handling = "shifted"); sort(y)
icuSetCollate(strength = "primary"); order(y)
icuSetCollate(strength = "primary "); order(y)
icuSetCollate(strength = "tertiary ", case_first = "lower", alternate_handling = "non_ignorable"); sort(y)
icuSetCollate(case_level = "on", strength = "primary "); order(y)
tryCatch(icuSetCollate(case_first = "on"), error = conditionMessage)
tryCatch(icuSetCollate("upper"), error = conditionMessage)
tryCatch(icuSetCollate(locale = 1), error = conditionMessage)
icuSetCollate(locale = "ASCII"); sort(y); icuGetCollate()
icuSetCollate(locale = "none"); sort(y); icuGetCollate()
icuSetCollate(locale = "sv"); sort(c("z", "ä", "a", "ö", "o", "å"))
icuSetCollate(locale = "de@collation=phonebook"); sort(c("Muller", "Müller", "Mueller", "Mulle"))
icuSetCollate(locale = "default"); sort(y); icuGetCollate()
invisible(Sys.setlocale("LC_COLLATE", "C")); sort(y); icuGetCollate()
invisible(Sys.setlocale("LC_COLLATE", "C.UTF-8")); sort(y); icuGetCollate()
