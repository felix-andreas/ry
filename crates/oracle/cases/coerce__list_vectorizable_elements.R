# A list coerces to an atomic vector when every element is a vector of length at most one, a
# list included; an empty vector or a list element becomes NA, and anything else is an error.
t <- function(expr) str(tryCatch(withCallingHandlers(expr, warning = function(w) { message("W: ", conditionMessage(w)); invokeRestart("muffleWarning") }), error = function(e) conditionMessage(e)))
t(as.logical(list(integer(0), list(), "TRUE", "x", 2L, list(3))))
t(as.integer(list(a = integer(0), b = list(), c = "7", d = 2.9)))
t(as.double(list(character(0), list(1), 1i)))
t(as.complex(list(list(), 2)))
t(as.raw(list(list(), 300, 2)))
t(as.character(list(list(), integer(0), 1)))
t(as.integer(list(expression(a), 1)))
t(as.integer(list(1:2, 1)))
t(as.integer(list(sum, 1)))
t(as.integer(list(factor("b", levels = c("a", "b")))))
t(as.logical(list(list(1L), 1L)))
t(as.vector(list(list(1L), 1L), "logical"))
t(as.vector(list(NULL, 1L), "logical"))
t(as.vector(list(list(1L)), "logical"))
t(as.integer(list(list(1L), 2)))
x <- list(1, list(2), integer(0)); storage.mode(x) <- "integer"; str(x)
x <- list(a = TRUE, b = list()); mode(x) <- "numeric"; str(x)
x <- structure(rep_len(list(list(deep = list(1L)), 1L), 4), units = "m")
r <- tryCatch({ mode(x) <- "logical"; x }, error = function(e) conditionMessage(e)); str(r)
y <- list(list(1L), 1L)
t({ storage.mode(y) <- "logical"; y })
