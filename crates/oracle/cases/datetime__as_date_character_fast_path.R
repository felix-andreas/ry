# as.Date() on character vectors, the shapes as.Date.character's native prologue covers next to
# the ones it hands to the R body: formats, tryFormats, format=, optional=, NA and empty strings,
# strings no format matches, names, factors, and when argument code runs.
show <- function(x) { print(x); str(unclass(x)); print(attributes(x)) }
caught <- function(expr) withCallingHandlers(
  tryCatch(expr, error = function(e) cat("error:", conditionMessage(e), "| call:", deparse(conditionCall(e)), "\n")),
  warning = function(w) {
    cat("warning:", conditionMessage(w), "| call:", deparse(conditionCall(w)), "\n")
    invokeRestart("muffleWarning")
  }
)
show(as.Date("2024-03-15"))
show(as.Date("2024/03/15"))
show(as.Date(c("2024-03-15", "1969-12-31", "1900-02-28", "2000-02-29", "0001-01-01", "9999-12-31")))
show(as.Date(c("2024-03-15", "2024/03/16", "junk", "2024-02-30", "2023-02-29")))
show(as.Date(c(NA, "", "2024-03-15", NA, "")))
show(as.Date(c(NA, "")))
show(as.Date(NA_character_))
show(as.Date(""))
show(as.Date(character(0)))
show(as.Date(c(a = "2024-03-15", b = "", c = NA)))
show(as.Date("2024-03-15 12:34:56"))
show(as.Date("2024-03-15T23:59:59"))
