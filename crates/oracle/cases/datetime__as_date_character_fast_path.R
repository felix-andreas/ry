# Argument code runs where the R body forces it: x inside charToDate(), format inside strptime().
depth <- function(label, value) { cat(label, "forced; calls:", length(sys.calls()), "\n"); value }
show(as.Date.character(depth("x", "2024-03-15")))
show(as.Date.character(depth("x", "15.03.2024"), format = depth("format", "%d.%m.%Y")))
show(as.Date.character(depth("x", "15/03/2024"), tryFormats = depth("tryFormats", c("%Y-%m-%d", "%d/%m/%Y"))))
show(as.Date(depth("x", "2024-03-15"), format = depth("format", "%Y-%m-%d")))
f <- function(s, fmt) as.Date(s, format = fmt)
show(f("15.03.2024", "%d.%m.%Y"))
g <- function(s, ...) as.Date(s, ...)
show(g("2024-03-15"))
show(g("15.03.2024", format = "%d.%m.%Y"))
show(g("15/03/2024", tryFormats = "%d/%m/%Y"))
h <- function(s, fmt) as.Date(s, format = fmt)
show(h("2024-03-15"))

# strptime() recycles x, with its names, to a longer format.
both <- c("%Y-%m-%d", "%Y/%m/%d")
show(as.Date(c(a = "2024-03-15"), format = both))
show(as.Date(c(a = "2024-03-15", b = "2024/03/16", c = "x"), format = c(both, both)))
r <- strptime(c(a = "2024-03-15", "2024/03/16"), c(both, both, both), tz = "GMT")
print(names(r))
print(attributes(r$year))
print(names(strptime(c(a = "2024-03-15", b = "2024-03-16"), "%Y-%m-%d", tz = "GMT")))
print(names(strptime(character(0), both, tz = "GMT")))
