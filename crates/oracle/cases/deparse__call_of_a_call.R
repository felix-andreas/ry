# A call whose function is itself a call takes parentheses unless that inner call's function
# is a name, a subset or a parenthesized expression.
show <- function(expr) cat(deparse(expr), "\n")
show(quote(f(1)(2)))
show(quote(f(1)(2)(3)))
show(quote(f()()()))
show(quote(f(1)(2)(3)(4)))
show(quote(a$b()))
show(quote(a$b()()))
show(quote(a$b()()()))
show(quote(a[[1]]()(2)))
show(quote(a[1](2)(3)))
show(quote(a::b()()))
show(quote((f)(1)))
show(quote((f)(1)(2)))
show(quote((function() 1)()))
show(quote((function(x) function() x)()()))
show(quote((a + b)()))
show(quote((a + b)()()))
show(quote((-a)()))
show(quote(`%o%`(f, g)(1)))
show(quote({f}(1)))
show(quote({f}(1)(2)))
show(quote(if (a) f else g))
show(as.call(list(quote(f(1)(2)), 3)))
show(as.call(list(as.call(list(quote(f(1)), 2)), quote(x))))
show(as.call(list(quote(if (a) f else g), 1)))
show(as.call(list(quote(function(x) x), 1)))
show(as.call(list(function(x) x, 1)))
show(as.call(list(sum, 1)))
h <- function(n) if (n == 0) function() sys.call() else function() h(n - 1)
print(h(0)())
k <- function() function() function() sys.call()
print(k()()())
print(body(function() f(1)(2)(3)))
print(deparse(quote(f(1)(2)(3)), control = "all"))
