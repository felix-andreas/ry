# Strings read from a file without a declared encoding are native ("unknown"), even when they are
# valid UTF-8; a declared encoding marks only the non-ASCII strings.
f <- tempfile()
v <- data.frame(`größe` = "Zed", `ä` = "abab", key = "aä", n = 1, check.names = FALSE)
write.csv(v, f, fileEncoding = "UTF-8")
x <- read.csv(f)
print(names(x)); print(lapply(x[2:4], Encoding))
x <- read.csv(f, check.names = FALSE)
print(names(x)); print(Encoding(names(x)))
x <- read.csv(f, encoding = "UTF-8", check.names = FALSE)
print(Encoding(names(x))); print(lapply(x[2:4], Encoding))
x <- read.csv2(f)
print(Encoding(x[[1]]))
x <- read.table(f, header = TRUE, sep = ",")
print(Encoding(x$key))
print(Encoding(scan(f, what = "", sep = ",", quiet = TRUE)))
print(Encoding(scan(f, what = "", sep = ",", quiet = TRUE, encoding = "latin1")))
print(Encoding(scan(f, what = "", sep = ",", quiet = TRUE, encoding = "UTF-8")))
print(Encoding(scan(f, what = list("", "", "", "", 0), sep = ",", skip = 1, quiet = TRUE)[[4]]))
x <- read.table(text = c("a b", "é ü"), header = TRUE)
print(Encoding(x$a))
con <- textConnection(c("p,q", "ö,z"))
x <- read.csv(con)
print(Encoding(x$p))
unlink(f)

# A pipe does not re-encode, so its lines carry no mark.
piped <- tempfile()
writeLines("äb", piped)
Encoding(readLines(pipe(paste("cat", piped))))
Encoding(scan(pipe(paste("cat", piped)), what = "", quiet = TRUE))
