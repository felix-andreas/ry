# Classes whose ancestors belong to class unions, defined inside a package namespace: the
# subclass records `setIs()` adds to each ancestor and the re-sorted `contains` lists a union
# re-caches for its subclasses, which ry's methods core does natively.
info <- new.env(hash = TRUE, parent = baseenv())
imports <- new.env(hash = TRUE, parent = .BaseNamespaceEnv)
attr(imports, "name") <- "imports:s4union"
ns <- new.env(hash = TRUE, parent = imports)
assign(".__NAMESPACE__.", info, envir = ns)
info$spec <- c(name = "s4union", version = "1.0")
info$exports <- new.env(hash = TRUE, parent = baseenv())
info$imports <- list(base = TRUE)
info$path <- tempdir()
info$dynlibs <- character()
info$S3methods <- matrix(NA_character_, 0L, 4L)
assign(".packageName", "s4union", envir = ns)
invisible(.Internal(registerNamespace("s4union", ns)))
contains <- function(class) vapply(getClassDef(class, where = ns)@contains, function(e) paste0(e@superClass, ":", e@distance), "")
subclasses <- function(class) vapply(getClassDef(class, where = ns)@subclasses, function(e) paste0(e@subClass, ":", e@distance, "[", paste(e@by, collapse = "/"), "]"), "")
setClass("Base", representation("VIRTUAL"), where = ns)
setClassUnion("BaseOrNULL", c("Base", "NULL"), where = ns)
setClass("C1", contains = "Base", slots = c(x = "numeric"), where = ns)
setClass("C2", contains = "C1", where = ns)
print(contains("C1")); print(contains("C2")); print(subclasses("BaseOrNULL"))
print(is(new("C2"), "BaseOrNULL")); print(extends("C2", "BaseOrNULL"))
setClass("M", slots = c(m = "numeric"), where = ns)
setClassUnion("U", "M", where = ns)
setClass("S", contains = "M", where = ns)
setClass("C", contains = "S", where = ns)
setClass("D", contains = "C", slots = c(d = "list"), where = ns)
setClassUnion("U3", "C", where = ns)
print(contains("D")); print(subclasses("U3"))
setClass("E", contains = "D", where = ns)
print(contains("D")); print(contains("E")); print(subclasses("U3")); print(subclasses("U"))
setClass("F", contains = "E", where = ns)
setClass("G", contains = "F", where = ns)
print(contains("G")); print(contains("D"))
setGeneric("h", function(x) standardGeneric("h"), where = ns)
setMethod("h", "M", function(x) "M", where = ns)
setMethod("h", "U3", function(x) "U3", where = ns)
setMethod("h", "BaseOrNULL", function(x) "BaseOrNULL", where = ns)
h <- get("h", ns)
for (class in c("M", "S", "C", "D", "E", "G", "C1", "C2")) cat(class, h(new(class)), "\n")
print(h(NULL)); print(is(new("G")))
