# Recording and replaying grid and base drawing through the engine's display list, checked by
# capturing the pixels on a ragg device before and after.
library(grid)
library(ragg)
checksum <- function() sum(as.numeric(dev.capture(native = TRUE)) %% 65521)
agg_capture(width = 240, height = 180)
dev.control("enable")
grid.rect(gp = gpar(fill = "tan"))
grid.circle(r = 0.3, gp = gpar(fill = "navy"))
before <- checksum()
recorded <- recordPlot()
class(recorded)
grid.newpage()
blank <- checksum()
replayPlot(recorded)
after <- checksum()
c(identical(before, after), identical(before, blank))
plot(1:5)
base <- checksum()
recorded <- recordPlot()
plot.new()
replayPlot(recorded)
identical(checksum(), base)
first <- dev.cur()
agg_capture(width = 240, height = 180)
invisible(dev.set(first))
invisible(dev.copy(which = dev.next()))
identical(checksum(), base)
graphics.off()
