# sequence() concatenates one run per element of nvec, recycling from and by.
print(sequence(c(3, 2, 0, 4)))
print(sequence(c(3L, 2L), from = c(10L, -1L)))
print(sequence(c(4, 3), by = c(2L, -3L)))
print(sequence(3:1, from = 5L, by = 0L))
print(sequence(integer()))
print(sequence(c(2, 3), from = 2147483646L))
print(tryCatch(sequence(c(1, 1), from = c(NA, 1L), by = NA), error = conditionMessage))
print(sequence(c(1, 1), from = 1L, by = NA))
print(tryCatch(sequence(c(2, NA)), error = conditionMessage))
print(tryCatch(sequence(-1), error = conditionMessage))
print(tryCatch(sequence(c(2, 1), from = c(1L, NA)), error = conditionMessage))
print(tryCatch(sequence(c(2, 3), by = c(1L, NA)), error = conditionMessage))
print(sequence(2, from = 1:3, recycle = TRUE))
print(sum(sequence(1:1000)))
