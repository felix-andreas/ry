# Sys.getenv, Sys.setenv and Sys.unsetenv: names, unset values, empty and non-ASCII values,
# the visibility of each result and the errors for unnamed or malformed arguments.
show <- function(expr) {
    value <- tryCatch(expr, error = function(e) paste("error:", conditionMessage(e)))
    str(value)
}
