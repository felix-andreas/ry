# A union of a class from another package recaches that class's subclasses, as GNU R does.
mkns <- function(name, imports_from = NULL) {
info <- new.env(hash = TRUE, parent = baseenv())
imports <- new.env(hash = TRUE, parent = .BaseNamespaceEnv)
attr(imports, "name") <- paste0("imports:", name)
ns <- new.env(hash = TRUE, parent = imports)
assign(".__NAMESPACE__.", info, envir = ns)
info$spec <- c(name = name, version = "1.0")
info$exports <- new.env(hash = TRUE, parent = baseenv())
info$imports <- list(base = TRUE)
info$path <- tempdir()
info$dynlibs <- character()
info$S3methods <- matrix(NA_character_, 0L, 4L)
assign(".packageName", name, envir = ns)
invisible(.Internal(registerNamespace(name, ns)))
ns
}
ns1 <- mkns("pone")
setClass("A", slots = c(x = "numeric"), where = ns1)
setClass("B", contains = "A", slots = c(y="numeric"), where = ns1)
setClass("C", contains = "B", slots = c(z="numeric"), where = ns1)
ns2 <- mkns("ptwo")
imp <- parent.env(ns2)
for (cl in c("A","B","C")) assign(paste0(".__C__", cl), get(paste0(".__C__", cl), ns1), envir = imp)
print(identical(getClass("C")@contains$A, getClass("A")@subclasses$C))
setClassUnion("Warm", c("logical", "complex"), where = ns2)
setClassUnion("U", c("A", "character"), where = ns2)
print(identical(getClass("C")@contains$A, getClass("A")@subclasses$C))
print(attributes(getClass("C")@contains$A@by))
x <- new("C", x=1, y=2, z=3); as(x, "A") <- new("A", x = 9); print(x@x)
cat(names(getClass("C")@contains), "\n")
