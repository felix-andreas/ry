# Output diverted by `sink` is flushed after every write, so the file can be read while the
# sink is still in place. Messages diverted with `type = "message"` go to the connection too.
path <- tempfile()
con <- file(path, open = "w+")
sink(con, type = "message")
cat("to stderr\n", file = stderr())
message("a message")
number <- sink.number(type = "message")
closing <- tryCatch(close(con), error = conditionMessage)
sink(NULL, type = "message")
print(number == getConnection(number))
print(closing)
print(readLines(path))
close(con)
print(sink.number(type = "message"))

path <- tempfile()
con <- file(path, "w")
sink(con)
cat("diverted\n")
lines <- readLines(path)
sink()
print(lines)
close(con)

path <- tempfile()
con <- file(path, "w")
writeLines("buffered", con)
close(con)
print(readLines(path))
