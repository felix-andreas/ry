# `readLines` to the end of a connection gives the same lines however the bytes arrive: line
# ends of every kind, embedded nuls, pushback, a partly read connection, and no final newline.
dir <- file.path(tempdir(), "read-lines-case")
unlink(dir, recursive = TRUE)
dir.create(dir)
put <- function(name, bytes) { path <- file.path(dir, name); writeBin(bytes, path); path }
text <- function(...) charToRaw(paste0(...))
show <- function(expr) {
  value <- withCallingHandlers(expr, warning = function(w) {
    cat("warning:", sub(dir, "<dir>", conditionMessage(w), fixed = TRUE), "\n")
    invokeRestart("muffleWarning")
  })
  print(value)
}

show(readLines(put("lf", text("one\ntwo\n\nfour\n"))))
show(readLines(put("crlf", text("one\r\ntwo\r\n\r\nfour\r\n"))))
show(readLines(put("cr", text("one\rtwo\r\rfour\r"))))
show(readLines(put("mixed", text("a\r\r\nb\n\rc\r\n\nd"))))
show(readLines(put("crend", text("a\nb\r"))))
show(readLines(put("partial", text("one\ntwo"))))
show(readLines(file.path(dir, "partial"), warn = FALSE))
show(readLines(put("empty", raw())))
show(readLines(put("blank", text("\n"))))
show(readLines(put("blanks", text("\n\n\n"))))
nul <- put("nul", c(text("ab"), as.raw(0), text("cd\nef\n"), as.raw(0), text("gh"), as.raw(0), text("\nlast")))
show(readLines(nul))
show(readLines(nul, skipNul = TRUE))
show(readLines(nul, warn = FALSE, skipNul = TRUE))
show(nchar(readLines(put("long", text(strrep("x", 200000), "\n", strrep("y", 70000), "\nz\n")))))
show(length(readLines(put("many", text(strrep("line\n", 50000))))))
show(charToRaw(readLines(put("latin", as.raw(c(0x63, 0x61, 0x66, 0xe9, 0x0a))), encoding = "latin1")))
show(Encoding(readLines(file.path(dir, "latin"), encoding = "latin1")))
show(Encoding(readLines(put("utf", text("café\nplain\n")), encoding = "UTF-8")))

# A connection that is already open: some lines one way, the rest the other.
con <- file(file.path(dir, "crlf"), "r")
show(readLines(con, n = 1))
show(readLines(con))
show(readLines(con))
close(con)
con <- file(file.path(dir, "lf"), "r")
pushBack(c("pushed one", "pushed\rtwo"), con)
show(readLines(con))
close(con)
con <- file(file.path(dir, "partial"), "r")
show(readLines(con, n = 1))
pushBack("again", con)
show(readLines(con))
close(con)
con <- file(file.path(dir, "cr"), "r")
show(readChar(con, 2))
show(readLines(con))
close(con)
con <- file(file.path(dir, "partial"), "r", blocking = FALSE)
show(readLines(con))
show(isIncomplete(con))
show(readLines(con))
close(con)
con <- file(file.path(dir, "lf"), "rb")
show(readLines(con, n = 2))
show(readLines(con))
close(con)

# Other kinds of connection.
show(readLines(textConnection(c("t one", "t two", ""))))
con <- textConnection("solo")
show(readLines(con)); close(con)
con <- rawConnection(text("r one\r\nr two"))
show(readLines(con)); close(con)
gz <- file.path(dir, "lines.gz")
con <- gzfile(gz, "w"); writeLines(c("g one", "g two", "", "g four"), con); close(con)
show(readLines(gz))
con <- gzfile(gz); show(readLines(con, n = 2)); close(con)
show(readLines(pipe("printf 'p one\\np two\\r\\np three'")))
show(tryCatch(readLines(file.path(dir, "missing")), error = function(e) "cannot open", warning = function(w) "warned"))
show(tryCatch(readLines(file.path(dir, "lf"), n = 9, ok = FALSE), error = conditionMessage))
show(readLines(file.path(dir, "lf"), n = 0))
show(readLines(file.path(dir, "lf"), n = 2))
unlink(dir, recursive = TRUE)
