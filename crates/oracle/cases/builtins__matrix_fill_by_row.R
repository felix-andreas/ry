# matrix() and array() fill every vector type in one pass, by column or by row, with recycling.
matrix(1:6, 2, byrow = TRUE)
matrix(c(1.5, 2.5, 3.5), 2, 3, byrow = TRUE)
matrix(letters[1:6], ncol = 2, byrow = TRUE)
matrix(letters[1:4], 2, 4)
matrix(list(1, "a", TRUE, NULL), 2, byrow = TRUE)
matrix(c(TRUE, NA), 3, 2, byrow = TRUE)
matrix(complex(real = 1:4, imaginary = -1), 2, byrow = TRUE)
matrix(as.raw(1:6), 3, byrow = TRUE)
matrix(1:6, 1, byrow = TRUE)
matrix(1:6, ncol = 1, byrow = TRUE)
matrix(1:3, 2, 3, byrow = TRUE)
suppressWarnings(matrix(1:4, 3, 3, byrow = TRUE))
matrix(numeric(), 2, 2, byrow = TRUE)
matrix(1:4, 0, 2, byrow = TRUE)
array(letters[1:3], c(2, 2, 2))
array(list(1, "b"), c(2, 2))
m <- matrix(sprintf("s%d", 1:12), 3, byrow = TRUE)
m[2, ]
