# A connection object names its slot; conn_id is a small serial number, as in GNU R.
f <- tempfile()
a <- file(f, "w")
id <- attr(a, "conn_id")
print(class(id))
print(is.na(strtoi(gsub("(<pointer:| |>)", "", capture.output(print(id))), 16L)))
x <- unserialize(serialize(list(con = a), NULL))
print(summary(x$con)$description == f)
print(identical(attr(x$con, "conn_id"), id))
close(a)
print(tryCatch(summary(a), error = conditionMessage))
b <- file(f, "w")
print(summary(a)$description == f)
close(b)
